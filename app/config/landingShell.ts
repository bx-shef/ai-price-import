// Оболочка публичных страниц — ОДИН источник фона и переднего плана (#368).
//
// ⚠ Что именно сломалось. Оболочка «тёмный бренд» была описана в двух местах: лендинг задавал её у
// себя в разметке, а юридические страницы ПОВТОРЯЛИ её у себя. Повторили половину: `bodyAttrs` с
// фоном скопировали, а цвет текста — он живёт на корневом элементе страницы, не в `useHead` — нет.
// На корне `<main>` не было НИКАКОГО `color`, поэтому заголовки, абзацы и ячейки таблиц наследовали
// начальное значение браузера (`canvastext`, то есть чёрный) и давали к фону `#05010f` контраст 1.02 —
// чёрным по чёрному. Это ровно те два адреса, которые открывает модератор Маркета. Пока фон и текст
// задаются порознь, «фон без текста» остаётся выразимым состоянием; здесь они лежат рядом, и гард
// требует брать их вместе.
//
// ⚠ Чего в причине НЕ было, хотя сначала так и было записано: «токены b24ui тут не разворачиваются».
// Разворачиваются. `b24ui-nuxt/dist/runtime/index.css` безусловно тянет `air-design-tokens`, а тот —
// `004_b24_context_dark.css`, который объявляет `--ui-color-base-*` на ОБЫЧНОМ селекторе `.dark`
// (обёртка `B24App` ему не нужна), и класс `.dark` вешает наш `theme-init` по `data-force-dark`.
// Стоявшие в `LegalDocument.vue` `base-3/4/5` резолвились в тёмные значения и давали 8.75 / 5.44 /
// 3.64 — все проходят. Нечитаемым был текст БЕЗ цвета, а не текст в токенах. Держим это здесь,
// потому что неверная причина уже один раз попала в документацию как «инвариант платформы».

/** Точное значение фона. Единственная рукописная копия — класс ниже собирается из него. */
export const SHELL_BG_HEX = '#05010f'

/**
 * Фон оболочки. Тот же класс уходит в `bodyAttrs`, иначе за краем контента виден белый лист.
 *
 * ⚠ Класс написан ЛИТЕРАЛОМ, а не собран из `SHELL_BG_HEX` шаблонной строкой: Tailwind v4 ищет
 * классы-кандидаты по тексту исходников, и `bg-[${…}]` он кандидатом не увидит — правило просто не
 * попадёт в CSS, а фон молча станет белым. Расхождение двух копий сторожит тест (он требует, чтобы
 * класс содержал хекс), — здесь нужен именно текст, а не вычисление.
 */
export const SHELL_BG_CLASS = 'bg-[#05010f]'

/**
 * Цвета вспомогательного текста и рамок документа.
 *
 * Ключи — имена цветов палитры: тест читает их значения из ОТГРУЖАЕМОЙ темы (палитра b24ui, а не
 * стоковая Tailwind — они заметно разные) и считает контраст к фону. Значения обязаны попадать в
 * разметку через `SHELL_VARS` ниже, иначе гард сторожил бы константу, которую никто не читает.
 */
export const SHELL_COLORS = {
  /** Основной текст документа. */
  text: 'slate-200',
  /** Строка издателя и прочий второстепенный текст. */
  muted: 'slate-400',
  /** Текст цитаты. */
  quote: 'slate-300',
  /** Ссылки — тот же класс акцента, что у лендинга. */
  link: 'cyan-400',
  /**
   * Рамки таблиц и `<hr>`. НЕ текст: к ним планка 3:1, а не 4.5:1 (WCAG 1.4.11 — нетекстовый контраст).
   *
   * ⚠ Числа отгружаемой палитры к нашему фону: `slate-500` — 7.79, `slate-700` — 3.99 (планку 3:1
   * проходит, но впритык), `slate-900` — 2.05 (не проходит). Берём `slate-500`: на тёмном фоне
   * «неброско» и «невидимо» на глаз неразличимы, а таблица в политике несущая — без видимых рамок
   * она читается слипшимся абзацем. ⚠ Первая версия этого комментария приводила числа СТОКОВОЙ
   * палитры Tailwind (`slate-700` — 1.99), которой приложение не отгружает: b24ui переопределяет
   * палитру целиком. Поэтому тест и читает цвета из темы b24ui, а не из `tailwindcss/theme.css`.
   */
  border: 'slate-500'
} as const

/**
 * Те же цвета — как CSS-переменные для `<style scoped>`.
 *
 * Без этого моста `SHELL_COLORS` оставался мёртвой конфигурацией: разбор показал мутацию, где все
 * цвета в компоненте переписаны на непроходящие, а девять тестов зелены — гард считал контраст
 * значений, которых в разметке нет. Теперь компонент читает ТОЛЬКО эти переменные.
 */
export const SHELL_VARS: Record<string, string> = Object.fromEntries(
  Object.entries(SHELL_COLORS).map(([role, name]) => [`--legal-${role}`, `var(--color-${name})`])
)

/**
 * Классы оболочки: фон и передний план ВМЕСТЕ.
 *
 * Именно эта пара — то, что копировали и скопировали наполовину. Одной строкой её невозможно взять
 * частично. Цвет текста — литерал по той же причине, что и фон (Tailwind сканирует текст); связь с
 * `SHELL_COLORS.text` держит тест, иначе гард считал бы контраст цвета, которого в разметке нет.
 */
export const SHELL_CLASS = `${SHELL_BG_CLASS} text-slate-200`

/** Пороги WCAG, по которым тест судит о читаемости. Вынесены сюда, чтобы стояли рядом с цветами. */
export const CONTRAST_MIN_TEXT = 4.5
export const CONTRAST_MIN_LARGE = 3

