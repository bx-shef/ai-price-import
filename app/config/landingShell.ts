// Оболочка публичных страниц — ОДИН источник фона и переднего плана (#368).
//
// ⚠ Почему это вообще отдельный файл. Оболочка «тёмный бренд» была описана в двух местах: лендинг
// задавал её у себя в разметке, а юридические страницы ПОВТОРЯЛИ её у себя. Повторили половину:
// `bodyAttrs` с фоном скопировали, а цвет текста — он живёт на корневом элементе страницы, не в
// `useHead` — нет. Получилось тёмно-серое по почти чёрному, и это ровно те два адреса, которые
// открывает модератор Маркета. Пока фон и текст задаются порознь, «фон без текста» остаётся
// выразимым состоянием; здесь они лежат рядом, и гард требует брать их вместе.
//
// ⚠ Почему обычный Tailwind, а не семантические классы b24ui (`text-muted`, `border-default`).
// У публичных страниц НЕТ обёртки `B24App`: в `app/layouts/` лежит один `clear.vue`, и он только
// для in-portal экранов, а лендинг и юридические страницы рендерятся прямо в `<NuxtPage>`. Значит
// тема b24ui в этом поддереве не разворачивается, и `var(--ui-color-base-*)` резолвится в то, что
// осталось от светлой темы. Именно этим дефект и был: в `LegalDocument.vue` стояли `base-3/4/5` —
// токены, которым здесь неоткуда взяться. На лендинге их не было никогда, он с самого начала писал
// цвет явным `text-slate-200`, и это оказалось единственной работающей половиной.

/** Фон оболочки. Тот же литерал уходит в `bodyAttrs`, иначе за краем контента виден белый лист. */
export const SHELL_BG_CLASS = 'bg-[#05010f]'
/** Точное значение фона — для расчёта контраста в тесте. Держим рядом с классом, а не в тесте. */
export const SHELL_BG_HEX = '#05010f'

/**
 * Классы оболочки: фон и передний план ВМЕСТЕ.
 *
 * Именно эта пара — то, что копировали и скопировали наполовину. Одной строкой её невозможно взять
 * частично.
 */
export const SHELL_CLASS = `${SHELL_BG_CLASS} text-slate-200`

/**
 * Цвета вспомогательного текста и рамок документа.
 *
 * Ключи — имена цветов палитры Tailwind: тест читает их значения из самой темы (`tailwindcss/theme.css`)
 * и считает контраст к фону. Так проверка не зависит от того, помню ли я, какой хекс у `slate-400`,
 * и не разъезжается при обновлении палитры — тот же приём, что у `tests/brandBadge.test.ts`.
 */
export const SHELL_COLORS = {
  /** Основной текст документа. */
  text: 'slate-200',
  /** Строка издателя и прочий второстепенный текст. */
  muted: 'slate-400',
  /** Текст цитаты. */
  quote: 'slate-300',
  /** Ссылки — тот же акцент, что у лендинга. */
  link: 'cyan-400',
  /**
   * Рамки таблиц и `<hr>`. НЕ текст: к ним планка 3:1, а не 4.5:1 (WCAG 1.4.11 — нетекстовый контраст).
   *
   * ⚠ Сначала здесь стоял `slate-700` — «рамка должна быть неброской». Гард посчитал: 1.99 к фону,
   * то есть рамки практически не видны, и таблица в политике читалась бы слипшимся абзацем. `slate-600`
   * тоже не проходит (2.73). Это ровно тот случай, ради которого контраст считается числом, а не
   * оценивается на глаз: «неброско» и «невидимо» на тёмном фоне неразличимы без расчёта.
   */
  border: 'slate-500'
} as const

/** Пороги WCAG, по которым тест судит о читаемости. Вынесены сюда, чтобы стояли рядом с цветами. */
export const CONTRAST_MIN_TEXT = 4.5
export const CONTRAST_MIN_LARGE = 3
