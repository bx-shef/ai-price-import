/**
 * Отступы оболочки in-portal экранов — ОДИН источник на шапку и на содержимое.
 *
 * Зачем константа, а не строка в трёх шаблонах: пара «отступ шапки + отступ колонки» обязана
 * совпадать, иначе заголовок встаёт левее карточек и экран читается как «шапка сама по себе,
 * страница сама по себе». Пока это были литералы в `app.vue`, `settings.vue` и `metrics.vue`,
 * четвёртый экран набрали бы руками — и разошлись бы молча.
 *
 * ⚠ ГЛАВНОЕ, И ЭТО КУПЛЕНО ОШИБКОЙ. Шапке отступ задаётся ЛОГИЧЕСКИМИ утилитами (`ps-*`/`pe-*`),
 * а НЕ коротким `px-*`. Первая редакция ставила навбару `px-4 sm:px-6` — и не работала вовсе:
 *
 *   • у `tailwind-merge` НЕТ правила конфликта `px` ↔ `ps`/`pe`, поэтому родные классы навбара
 *     (`ps-2 pe-4 lg:ps-4 lg:pe-4`) не вытеснялись, а оставались рядом с нашими;
 *   • дальше решает CSS, а там `padding-inline-start`/`-end` — длинные свойства и идут ПОСЛЕ
 *     короткого `padding-inline`, то есть побеждали родные значения.
 *
 * Итог: на `≥lg` шапка получала свои 16 px против наших 24 px — ровно на том широком экране, ради
 * которого правка и делалась. Тест при этом был зелёным: он проверял НАЛИЧИЕ пропа, а не результат.
 * Отсюда правило: перекрывая классы компонента b24ui, пиши утилиту ТОЙ ЖЕ формы, что у него, и
 * покрывай ВСЕ его брейкпоинты — иначе `tailwind-merge` не увидит конфликта.
 */

/** Horizontal padding of the content column (our own element — no merge involved). */
export const PORTAL_CONTENT_X = 'px-4 sm:px-6'

/**
 * Horizontal padding for `B24DashboardNavbar`'s root, in logical utilities.
 *
 * ⚠ Перечислены ВСЕ брейкпоинты родного класса (база и `lg`), иначе `lg:ps-4 lg:pe-4` переживают
 * подмену и снова расходятся с колонкой на широком экране.
 */
export const PORTAL_NAVBAR_X = 'ps-4 pe-4 sm:ps-6 sm:pe-6 lg:ps-6 lg:pe-6'
