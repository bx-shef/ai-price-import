// Реестр редакций юридических документов (#415). Данные, не логика.
//
// Зачем архив вообще. Репозиторий закрытый, значит история файлов перестала быть публичным
// доказательством содержания документов. При этом п. 9.3.7 EULA и п. 13.4 Политики обещают, что
// изменения не имеют обратной силы: к отношениям, возникшим до вступления новой редакции,
// применяется прежний текст. Без публичного архива это обещание нечем подкрепить — показать
// клиенту или суду, какая редакция действовала в день спорного импорта, было бы невозможно.
//
// Почему редакции лежат ОТДЕЛЬНЫМИ ФАЙЛАМИ (`docs/archive/<документ>/<дата>.md`), а не собираются
// из git на сборке: закрытый репозиторий доказательством не является, а закоммиченный и
// опубликованный файл — является. Плюс сборка перестаёт зависеть от глубины истории.
//
// ⚠ Файл архивной редакции НЕ РЕДАКТИРУЕТСЯ ЗАДНИМ ЧИСЛОМ никогда, даже ради опечатки: он был
// опубликован именно таким. Пока редакция действующая, её файл обязан совпадать с живым документом
// байт в байт — это сторожит тест; после замены он замирает навсегда.

export interface LegalEditionEntry {
  /** Дата редакции `ГГГГ-ММ-ДД` — она же постоянный адрес: `/eula/archive/2026-08-08`. */
  date: string
  /** Дата вступления в силу, как напечатана в документе (`ДД.ММ.ГГГГ`). */
  effective: string
  /**
   * Дата замены (`ДД.ММ.ГГГГ`) — когда редакция перестала действовать.
   * `null` у действующей: у неё в таблице стоит прочерк.
   */
  supersededAt: string | null
  /**
   * SHA-256 файла редакции — **отпечаток опубликованного текста**.
   *
   * ⚠ Без него неизменяемость архива держалась на комментарии. Байт-равенство сверяет снимок с
   * живым документом, но только пока редакция ДЕЙСТВУЮЩАЯ: у заменённой сверять не с чем, и её
   * файл можно было отредактировать задним числом — ровно то, что шапка запрещает, — при зелёном
   * CI. Отпечаток закрывает и второй случай: правку ещё-действующей редакции без смены даты
   * («поправим опечатку») равенство пропускало, потому что менялись обе копии сразу.
   */
  sha256: string
}

export interface LegalArchiveDoc {
  /** Сегмент адреса: `/eula`, `/privacy`, `/site-terms`, `/site-privacy`. */
  slug: string
  /**
   * Документ прямо обещает, что изменения НЕ имеют обратной силы.
   *
   * ⚠ Флаг, а не общий текст на всех: это утверждали все четыре страницы архива, а в
   * `site-terms.md` и `site-privacy.md` такого пункта нет вовсе (раздел об изменениях состоит из
   * публикации, вступления в силу и архива). Печатать за издателя обязательство сильнее, чем в
   * самом документе, — хуже, чем не печатать ничего.
   */
  noRetroactivity: boolean
  /** Заголовок документа — им подписаны и архив, и страница редакции. */
  title: string
  /** Имя файла в `docs/` (без расширения) — источник действующего текста. */
  sourceFile: string
  /** Редакции, новая первой. */
  editions: LegalEditionEntry[]
}

