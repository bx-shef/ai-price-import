import type { LlmProvider } from '~~/server/agent/llmConfig'

// Как ИИ-сервис называется ЧЕЛОВЕКУ (#437). Данные, а не логика: `llmConfig.label` — техническая
// метка для журналов и телеметрии (`bitrixgpt`, `deepseek`), и печатать её посетителю нельзя.
//
// ⚠ Название подставляется из АКТИВНОЙ конфигурации, а не пишется в разметке списком возможных.
// Тогда текст физически не может ни соврать, ни сказать лишнего: работает BitrixGPT — написано
// «BitrixGPT»; переключились на DeepSeek — текст переключился вместе с ним, без правки кода.
// Прежний баннер пугал посетителя гипотезой, которая в текущей конфигурации не наступает:
// автоматического переключения между провайдерами в коде нет вовсе — `resolveLlmConfig` зовётся
// один раз на старте, и чтобы данные ушли резервному провайдеру, владелец должен сам поменять
// переменную окружения и перезапустить сервис. То есть за предупреждение о том, чего мы не делаем,
// платили конверсией.
//
// ⚠ ВЕРСИЮ МОДЕЛИ НЕ НАЗЫВАЕМ. В коде заданы `bitrix/bitrixgpt-5.5` и `deepseek-v4-flash`, но обе
// перекрываются переменными окружения — на проде может работать не та версия, что названа на
// странице, и расхождение никак себя не проявит. Называем СЕРВИС.

/**
 * Витринные названия и ЮРИСДИКЦИЯ — по провайдеру.
 *
 * ⚠ Ключ — типизированный `provider`, а НЕ `label`. У `label` документированная роль «метка для
 * журналов и телеметрии», и в ветке `custom` он берётся из `LLM_LABEL`, то есть задаётся владельцем
 * инсталляции: `LLM_PROVIDER=custom` + `LLM_LABEL=bitrixgpt` + свой адрес заставили бы страницу
 * уверенно написать «BitrixGPT», пока документ уходит совсем другому получателю. В облаке это
 * закрыто фатальными проверками окружения, но ключевать раскрытие по подконтрольной строке нельзя
 * в принципе — union такой подмены не допускает.
 *
 * ⚠ Юрисдикция названа: это ровно тот параметр, из-за которого посетитель может отказаться отдать
 * документ, и в Политике сайта он вынесен отдельной колонкой (§4.2). Одно слово про РАБОТАЮЩЕГО
 * провайдера не воскрешает убранную гипотезу про резервный канал и снимает потерю раскрытия.
 */
const DISPLAY: Partial<Record<LlmProvider, { name: string, vendor: string }>> = {
  bitrixgpt: { name: 'BitrixGPT', vendor: 'нейросеть Битрикс24, обработка в России' },
  deepseek: { name: 'DeepSeek', vendor: 'обработка в КНР' }
}

/**
 * Запасное описание, когда провайдер не из известных (инсталляция клиента со своим ключом).
 *
 * ⚠ Не «ИИ-сервис»: в разметке рядом стоит слово «ИИ-сервис», и получалось «ИИ-сервис ИИ-сервис».
 * Здесь честное «внешний провайдер» — посетителю важно, что получатель ВНЕШНИЙ, а не как его зовут.
 */
const FALLBACK = { name: 'внешний провайдер', vendor: '' } as const

/**
 * Как назвать работающий сервис в тексте для посетителя.
 *
 * ⚠ `custom` в инсталляции клиента сюда не попадает намеренно: там получателя выбирает владелец
 * инсталляции, и назвать его за него мы не можем — «внешний провайдер» честно и ничего не
 * выдумывает.
 */
export function llmDisplayName(provider: LlmProvider | undefined): { name: string, vendor: string } {
  return (provider && DISPLAY[provider]) || FALLBACK
}
