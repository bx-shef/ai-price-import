// Пределы объявления издателя (#469). Данные, не логика — лукап живёт в `app/utils/announcement.ts`.

/** Заголовок: одна строка, её читают первой и целиком. */
export const MAX_ANNOUNCEMENT_TITLE = 120

/**
 * Текст объявления.
 *
 * ⚠ Предел не косметический: объявление показывается модальным окном поверх чужой CRM, а на
 * телефоне — шторкой снизу. Простыня на два экрана там не читается, её закрывают не читая, а
 * второй попытки нет — закрытое объявление человек больше не увидит (решение владельца).
 */
export const MAX_ANNOUNCEMENT_TEXT = 600

/** Подпись кнопки-ссылки. */
export const MAX_ANNOUNCEMENT_CTA = 40

/**
 * Кап картинки в БАЙТАХ ИСХОДНОГО ФАЙЛА (не строки base64).
 *
 * ⚠ Картинка едет в объявлении целиком (решение владельца: base64, не ссылка) — то есть лежит в
 * Redis и приезжает в браузер каждого сотрудника каждого портала. 256 КБ — это уже вполне
 * приличная картинка-баннер, а вчетверо больше означало бы мегабайт в ответе роута, который зовут
 * при каждом открытии рабочего экрана.
 */
export const MAX_ANNOUNCEMENT_IMAGE_BYTES = 256 * 1024

/**
 * Разрешённые типы картинки.
 *
 * ⚠ Список закрытый и БЕЗ `image/svg+xml`: SVG это документ со скриптами, и вставленный в чужой
 * портал он исполняется в контексте нашей страницы. Растровые форматы такого не умеют.
 */
export const ANNOUNCEMENT_IMAGE_TYPES = ['image/png', 'image/jpeg', 'image/webp', 'image/gif'] as const

/** Сколько дней объявление живёт по умолчанию, если срок не задан руками. */
export const DEFAULT_ANNOUNCEMENT_DAYS = 14

/** Предел срока: объявление — это новость, а не постоянный элемент интерфейса. */
export const MAX_ANNOUNCEMENT_DAYS = 90

/**
 * Предел тела запроса на публикацию.
 *
 * ⚠ Считается ОТ КАПА КАРТИНКИ, а не выбирается отдельно: base64 раздувает байты в ~4/3, плюс запас
 * на текст и заголовки. Два независимых числа разъехались бы молча — картинка проходила бы проверку
 * содержимого и упиралась в тело, а оператор видел бы «слишком большое тело» на картинке, которую
 * форма только что приняла.
 */
export const MAX_ANNOUNCEMENT_BODY_BYTES = Math.ceil(MAX_ANNOUNCEMENT_IMAGE_BYTES * 4 / 3) + 64 * 1024
