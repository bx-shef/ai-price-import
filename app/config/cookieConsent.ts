// Тексты и параметры уведомления о cookie (#404). Данные — здесь, логика — в
// `app/utils/cookieConsent.ts`, показ — в `CookieBanner.vue`.

/**
 * Ключ решения в `localStorage`.
 *
 * ⚠ Решение хранится в браузере посетителя, а не у нас, и это не лень: лендинг пререндерится, у
 * анонимного посетителя нет ни сессии, ни идентификатора, и заводить их РАДИ УЧЁТА СОГЛАСИЯ значило
 * бы начать собирать ровно те данные, о которых спрашиваем.
 */
export const CONSENT_KEY = 'cookie-consent'

/**
 * Версия текста согласия. Меняется вместе со смыслом вопроса (новый приёмник данных, новая
 * категория файлов) — тогда прежнее решение перестаёт быть ответом на заданный вопрос, и баннер
 * показывается снова. Косметическая правка формулировки версию НЕ меняет: дёргать посетителя из-за
 * запятой — тот же самый шум, ради которого решение и запоминают.
 */
export const CONSENT_VERSION = 1

/**
 * Адреса, на которых уведомление показывается.
 *
 * ⚠ Список — БЕЛЫЙ, а не чёрный. Лендинг и экраны внутри портала — одно приложение, и «показывать
 * везде, кроме перечисленного» означало бы, что каждая новая портальная страница по умолчанию
 * получает баннер: внутри фрейма Битрикса он бессмыслен (согласие даёт портал) и вдобавок закроет
 * половину рабочего экрана на телефоне. Забытая публичная страница — «баннера нет там, где он
 * нужен», забытая портальная при чёрном списке — «баннер поверх чужой CRM».
 *
 * ⚠ Архив редакций ВЫВОДИТСЯ из реестра, а не переписывается сюда руками. Рукописный список
 * пропустил двенадцать публичных адресов (`/<документ>/archive` и постоянные адреса редакций): они
 * пререндерятся, лежат в карте сайта и открываются прямо из поиска — посетитель читал бы там
 * «счётчик запускается только после вашего согласия», не видя, где это согласие дать. И список
 * по построению растёт: каждая новая редакция добавляет ещё два адреса.
 */
export const CONSENT_PATHS: readonly string[] = ['/', ...LEGAL_ARCHIVE.map(d => `/${d.slug}`), ...allArchiveRoutes()]

