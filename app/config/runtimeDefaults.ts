// Умолчания публичных настроек, устойчивые к ПУСТОЙ переменной окружения (#305).
//
// ЗАЧЕМ. Nitro накатывает переменные окружения поверх `runtimeConfig`, а `docker compose`
// материализует строку `KEY=` как ЗАДАННОЕ пустое значение. `applyEnv` делает
// `obj[key] = envValue ?? obj[key]`, и `destr('')` возвращает `''`, а не `undefined` — то есть
// пустая строка ВЫИГРЫВАЕТ у запечённого в образ значения и у умолчания в коде.
//
// ⚠ Здесь чинится второе последствие #305, и чинится ИМЕННО В КОДЕ, а не только в примере. В
// `nuxt.config.ts` умолчания формы заявки стоят через `process.env.X || 'дефолт'` — но это читается
// НА СБОРКЕ. На развёртывании одним процессом Nitro (Вайбкод) пустая переменная перебивает значение
// уже в РАНТАЙМЕ, и лендинг остаётся без формы заявки — молча, у того, кто просто скопировал
// `.env.example` в `.env`. Документ до 13.08.2026 утверждал обратное («пустая строка её не
// выключает»), и это было верно только для статической выкладки за nginx.

/** Первое непустое значение. Пустая строка и пробелы считаются «не задано». */
export function firstFilled(...values: unknown[]): string {
  for (const v of values) {
    if (typeof v === 'string' && v.trim()) return v.trim()
  }
  return ''
}

