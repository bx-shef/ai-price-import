<script setup lang="ts">
import { computed } from 'vue'
import { screenState } from '~/utils/screenState'

// Один источник состояния загрузки для всех экранов внутри портала (#408).
//
// ⚠ Смысл обёртки — сделать «экран, забывший показать загрузку» невозможным ПО ПОСТРОЕНИЮ, а не по
// внимательности. До неё состояние было ровно на одном экране из трёх: `/app` его имел (#256), а
// `/settings` и `/metrics` рисовали содержимое сразу и утверждали то, чего ещё не знали. Три
// независимые реализации одного состояния разъехались бы; здесь правило одно и чистое
// (`utils/screenState.ts`), а различается только заглушка — она обязана повторять раскладку
// СВОЕГО экрана, иначе контент появится не на месте и экран перестроится.
const props = defineProps<{
  /** Первая попытка загрузки завершилась (успехом или отказом). */
  loaded: boolean
  /** Текст ошибки загрузки. Пусто — ошибки нет. */
  error?: string | null
  /** Экран работоспособен без серверных данных (вне портала). Тогда состояние сразу «готово». */
  inert?: boolean
}>()

const state = computed(() => screenState({ loaded: props.loaded, error: props.error, inert: props.inert }))
</script>

<template>
  <!-- Заглушка каждого экрана своя: контент обязан появиться НА МЕСТЕ скелетона. -->
  <div
    v-if="state === 'loading'"
    aria-busy="true"
  >
    <!-- ⚠ Объявление — ОДНО и текстом внутри региона, а не через `aria-label`: метка на
         live-region читается непоследовательно (программы чтения объявляют содержимое, а не имя).
         Сама заглушка скрыта: `B24Skeleton` вешает `role="alert"` на каждую плашку, их в заглушках
         от 7 до 17, и вложенные регионы перебивали внешний — вместо «Загружаем данные» человек
         слышал серию английских «loading» на русском экране. -->
    <span
      role="status"
      class="sr-only"
    >Загружаем данные</span>
    <div aria-hidden="true">
      <slot name="skeleton" />
    </div>
  </div>
  <!-- Отказ — отдельный исход. Вечный скелетон вместо ошибки заставляет ждать бесконечно. -->
  <!-- ⚠ `warning`, а не `alert`: красный в проекте зарезервирован за жёсткими отказами, а неудача
       чтения восстановима. `role="alert"` проставлен явно — у `B24Alert` своей роли нет, и исход
       «не удалось загрузить» программе чтения не сообщался вовсе. -->
  <B24Alert
    v-else-if="state === 'error'"
    role="alert"
    color="air-primary-warning"
    title="Не удалось загрузить данные"
    :description="error || 'Попробуйте обновить страницу.'"
  />
  <slot v-else />
</template>
