// Стенд проверки слайдеров (#477): наблюдение вместо чтения справочника.
//
// ЗАЧЕМ. Про слайдеры мы дважды рассуждали вместо того, чтобы посмотреть, и оба раза это стоило
// времени: в #472 список параметров оказался неполным, а в #443 открытым остался несущий вопрос —
// `openSliderAppPage` резолвит промис в момент ОТКРЫТИЯ или в момент ЗАКРЫТИЯ слайдера? Справочник
// говорит «после закрытия», транспорт SDK устроен под это, а наш собственный код написан так, будто
// ждёт немедленного резолва (`if (await openMain()) return` читается как «открылось — выходим»).
// Одно из двух неверно, и живой проверки не было ни разу.
//
// ⚠ ГЛАВНОЕ ЗДЕСЬ — ВРЕМЯ, а не «сработало ли». Кнопка, печатающая «ок», отвечает на вопрос
// «открылось?», а спор идёт о вопросе «когда вернулось?». Поэтому запись фиксирует ОБА момента:
// клик и резолв, — и разницу между ними. Если резолв приходит через секунды после клика и ровно
// тогда, когда человек закрыл слайдер, — вопрос закрыт наблюдением, а не толкованием.

/** Одна строка журнала стенда. */
export interface ProbeEntry {
  /** Что нажали — «11», «12», «21», «22», «вход». */
  label: string
  /** Метка времени клика (мс от старта страницы). */
  startedMs: number
  /** Сколько прошло от клика до возврата управления. `null` — ещё не вернулось. */
  elapsedMs: number | null
  /** Что вернул вызов; для отказа — класс, а не текст исключения. */
  result: string
}

/** Текст строки для показа на экране. Чистый — тестируется без браузера. */
export function formatProbeEntry(e: ProbeEntry): string {
  const when = `${(e.startedMs / 1000).toFixed(2)} с`
  // ⚠ «ждём…» — не украшение: пока строка в этом состоянии, видно, что управление НЕ вернулось.
  // Именно так выглядит резолв на закрытии, и без промежуточного состояния его нельзя отличить от
  // мгновенного возврата — журнал показал бы обе картины одинаково, только с разными числами.
  const took = e.elapsedMs === null ? 'ждём…' : `${e.elapsedMs} мс`
  return `[${when}] ${e.label}: ${took} → ${e.result}`
}

/**
 * Класс исхода вызова слайдера — без текста исключения.
 *
 * ⚠ Тот же принцип, что во всём проекте: наружу идёт класс, а не строка портала. Стенд смотрят на
 * телефоне и переписывают наблюдения в задачу руками — простыня стектрейса там бесполезна.
 */
export function probeOutcome(value: unknown, failed: boolean): string {
  if (failed) return 'ОТКАЗ (вызов бросил)'
  if (value === true) return 'true'
  if (value === false) return 'false (SDK отказал или мы вне фрейма)'
  if (value === undefined) return 'undefined (вернулось без значения)'
  return String(value)
}
