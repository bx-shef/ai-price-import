// Как открыт главный экран (#262).
//
// Приложение открывают тремя путями, и до сих пор все три рисовали один и тот же рабочий экран:
//
//  1. прямой ссылкой / пунктом левого меню (`/marketplace/app/<id>/`) — БАЗОВЫЙ фрейм;
//  2. слайдером — это делаем мы сами (`openSliderAppPage({ place })`);
//  3. мобильным приложением Битрикс24.
//
// По решению владельца в случае 1 главная должна открываться слайдером, а базовый фрейм остаётся
// пусковой страницей. Это не косметика: рабочий экран держит опрос статусов, чтение метрик и
// настроек, подписку на pull и попап оценки. Оставь его и под слайдером — всё это крутилось бы в
// двух фреймах разом (двойной опрос, двойные таймеры, модалка оценки всплывает в фоне).
//
// Признак слайдера — НАШ собственный `place`, а не `IFRAME=Y`: `place` мы ставим сами, поэтому он
// однозначен, и открытый нами слайдер не пытается открыть себя снова. `IFRAME` учитываем вторым
// признаком — на случай, если портал откроет нас слайдером без нашего `place`.

export type AppLaunchMode = 'launcher' | 'work'

export interface LaunchInput {
  /** Мы внутри фрейма портала (init() вернул клиента). */
  inFrame: boolean
  /** `place` из PLACEMENT_OPTIONS — непустой у слайдера, открытого нами. */
  place?: string | null
  /** SDK-признак слайдера (`placement.options.IFRAME === 'Y'`). */
  sliderMode?: boolean
  /** Мобильное приложение Битрикс24 (b24ui `useDevice`). */
  isMobile?: boolean
}

/**
 * Пусковая страница или рабочий экран.
 *
 * `launcher` — ровно один случай: базовый фрейм портала, не слайдер, не мобильное. Всё остальное
 * (слайдер, мобильное, открытие вне портала) — рабочий экран, как и было. Вне портала лаунчер был
 * бы тупиком: открыть слайдер там нечем.
 */
export function appLaunchMode({ inFrame, place, sliderMode, isMobile }: LaunchInput): AppLaunchMode {
  if (!inFrame) return 'work'
  if (isMobile) return 'work'
  if (sliderMode) return 'work'
  if (place) return 'work'
  return 'launcher'
}

/** Ключ отметки «этот таб уже открывал главную слайдером» и окно, в котором повтор считается циклом. */
export const MAIN_SLIDER_MARK_KEY = 'b24.mainSliderOpenedAt'
export const MAIN_SLIDER_COOLDOWN_MS = 5000

/**
 * Можно ли открывать главную слайдером автоматически.
 *
 * Страховка от бесконечного открытия. Признак «мы уже в слайдере» — наш `place` из
 * PLACEMENT_OPTIONS; он работает, но если портал когда-нибудь их не донесёт, лаунчер откроет
 * слайдер, тот увидит себя базовым фреймом и откроет ещё один — и так без предела. Отметка времени
 * в пределах вкладки это обрывает: второе автооткрытие подряд не делаем, показываем кнопку.
 *
 * Только про АВТО-открытие. Кнопку «Открыть импорт» человек нажимает сам — её не ограничиваем.
 */
export function canAutoOpenMain(lastOpenedAt: number | null, nowMs: number, cooldownMs = MAIN_SLIDER_COOLDOWN_MS): boolean {
  if (lastOpenedAt === null || !Number.isFinite(lastOpenedAt)) return true
  // Метка из будущего (переведённые часы) — не повод блокировать открытие навсегда.
  if (lastOpenedAt > nowMs) return true
  return nowMs - lastOpenedAt >= cooldownMs
}
