import type { PullEventParams } from './settingsSync'

// Живая доставка объявления издателя (#478). Пара к `settingsSync.ts`: та же труба портала
// (`pull.application.event.add`), но другая команда и другой отправитель.
//
// ЗАЧЕМ. До этого объявление доезжало ТОЛЬКО когда сотрудник открывал рабочий экран: диалог
// спрашивает сервер при монтировании. Вкладку рабочего экрана в портале не перезагружают сутками —
// это записано прямо в обосновании срока показа, — то есть канал «сказать всем клиентам сразу»
// говорил не сразу, а когда-нибудь: кому-то через час, кому-то завтра, а тому, кто держит вкладку
// открытой, — никогда. Для новости об акции со сроком это обесценивает сам канал: акция кончится
// раньше, чем объявление кого-то догонит.
//
// ⚠ КОМАНДА СВОЯ, а не `reload.options`. Одна команда на оба означала бы лишний запрос настроек на
// каждое объявление и лишний запрос объявления на каждое сохранение настроек — то есть удвоение
// обращений к нашему серверу ради экономии одной строки.
//
// ⚠ В СОБЫТИИ НЕТ САМОГО ОБЪЯВЛЕНИЯ, и это не оптимизация. Во-первых, объявление несёт картинку в
// base64 — гнать её через канал портала каждому сотруднику было бы расточительно. Во-вторых и
// главное: содержимому события доверять нельзя. Событие — только сигнал «сходи проверь», а текст,
// картинку и срок клиент берёт своим проверенным запросом. Тот же принцип, что у настроек.

/** Команда, по которой открытые экраны идут перечитывать объявление. */
export const ANNOUNCEMENT_PULL_COMMAND = 'announcement.check'

/**
 * Params for `pull.application.event.add` telling every open screen to re-check the announcement.
 *
 * ⚠ Событие ОДНО и на публикацию, и на снятие: клиент в обоих случаях делает одно и то же — идёт и
 * спрашивает, есть ли действующее объявление. Разные команды на «появилось» и «сняли» потребовали бы
 * от клиента верить событию на слово, а он ему не верит по построению (см. шапку).
 */
export function buildAnnouncementEvent(moduleId: string): PullEventParams {
  return { COMMAND: ANNOUNCEMENT_PULL_COMMAND, PARAMS: {}, MODULE_ID: moduleId }
}

/**
 * Разброс перед запросом объявления после сигнала.
 *
 * ⚠ Сигнал приходит ВСЕМ сотрудникам ВСЕХ порталов одновременно — момент выбирает издатель. Запрос
 * за объявлением проверяет фрейм-токен, то есть стоит обращения к базе и исходящего вызова к
 * порталу; без разброса штатная публикация сама себе устраивала бы всплеск на самом дорогом пути.
 * ⚠ Величина выбрана из того, что объявление — НЕ срочность: несколько секунд разницы человек не
 * заметит, а пик размазывается. Для настроек такой задержки нет и не нужно: там событие шлёт портал
 * сам себе, и получателей столько, сколько вкладок у одного портала.
 */
export const ANNOUNCEMENT_CHECK_JITTER_MS = 8000
