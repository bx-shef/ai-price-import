// Какое из состояний показывает главный экран (#256).
//
// Раньше состояний было два — «баннер» и «работа», — и пока настройки грузились, экран считал, что
// настраивать ничего не надо, и рисовал ВЕСЬ рабочий контент. Через мгновение ответ приходил, контент
// схлопывался, появлялся баннер «Сначала настройте». Выглядело как сбой.
//
// Состояний на самом деле три, и «неизвестно» — полноценное первое: пока исход загрузки настроек не
// известен, нельзя показывать ни работу, ни баннер.

export type AppScreenState = 'loading' | 'launcher' | 'setup' | 'work'

// ⚠ Состояния `consent` здесь БОЛЬШЕ НЕТ (#438, решение владельца 2026-08-05), и это не упрощение
// ради краткости. Маркет Битрикс24 собирает принятие условий ДО установки — тремя галочками со
// ссылками в самом диалоге установки, — а п. 4.3.2 Лицензионного соглашения привязывает
// подтверждение прав к ДЕЙСТВИЮ ЗАГРУЗКИ приложения, а не к отдельному экрану. Запись о принятии
// видна издателю в личном кабинете Маркета. Свой экран поверх этого добавлял не доказательство, а
// ещё одну дверь между клиентом и первым импортом.
// ⚠ Не восстанавливать «на всякий случай»: серверный гейт под него структурно недостижим — без
// принятия нет установки, без установки нет токена портала, то есть до нашего кода дело не
// доходит вовсе. Гейт, который нельзя обойти, потому что до него нельзя добраться, защищает не
// приложение, а только видимость проверки.

export interface ScreenInput {
  /** Как открыто приложение (#262); `undefined` — ещё не определили. */
  launch?: 'launcher' | 'work'
  /** Загрузка настроек завершилась — неважно, успешно или нет. */
  settingsResolved: boolean
  /** Настройки прочитаны и остались дефолтными → приложение ещё не настроено. */
  needsSetup: boolean
}

/** Единственное правило показа. Инвариант: до `settingsResolved` — всегда `loading`. */
export function appScreenState({ launch, settingsResolved, needsSetup }: ScreenInput): AppScreenState {
  // Режим открытия решается раньше всего: в базовом фрейме рабочий экран вообще не поднимается,
  // поэтому ждать загрузки настроек там нечего и незачем (#262).
  if (!launch) return 'loading'
  if (launch === 'launcher') return 'launcher'
  if (!settingsResolved) return 'loading'
  return needsSetup ? 'setup' : 'work'
}
