// Что оператор читает про рассылку объявления (#478) и когда она вообще запускается.
//
// ⚠ Обе функции жили в разметке и в роуте, и разбор показал цену: условие запуска в роуте не
// покрывал НИ ОДИН тест, а мутация «рассылать не только на публикацию, но и на предпросмотр»
// превращала каждое нажатие «Проверить» в REST-обход всех порталов клиентов. Правило, у которого
// такая цена ошибки, обязано жить там, где его можно проверить.

/** Итог рассылки, каким его видит оператор. `null` — рассылку не удалось даже начать. */
export interface DeliveryReport {
  total: number
  sent: number
  failed: number
  truncated: boolean
}

/**
 * Действия консоли оператора, после которых рассылается сигнал.
 *
 * ⚠ Список ПОЛОЖИТЕЛЬНЫЙ, а не «всё кроме предпросмотра»: отрицательная форма (`!== 'preview'`)
 * молча включила бы рассылку для любого нового действия, которое здесь однажды появится.
 */
const BROADCAST_ACTIONS = new Set(['publish', 'clear'])

/**
 * Whether publishing/clearing succeeded and therefore warrants a broadcast.
 *
 * ⚠ Два условия, и оба несущие. ДЕЙСТВИЕ: предпросмотр ничего не меняет — рассылать по нему значит
 * дёргать все порталы клиентов на каждое нажатие «Проверить». СТАТУС: отвергнутая публикация
 * (не прошла проверка, нет хранилища) объявления не создала, и сигнал «сходи проверь» отправил бы
 * всех за тем, чего нет.
 */
export function shouldBroadcast(action: unknown, status: number): boolean {
  return status < 400 && typeof action === 'string' && BROADCAST_ACTIONS.has(action)
}

/**
 * Строка про доставку для оператора.
 *
 * ⚠ Печатается ВСЕГДА, включая «доставлено всем»: молчание пришлось бы толковать, а провалившаяся
 * рассылка выглядит ровно как «никто не открывал экран» — владелец ждал бы реакции на объявление,
 * которого никто не получил.
 * ⚠ «Рассылку не начали» и «порталов нет» — РАЗНЫЕ вещи, и текст обязан их различать: первое авария
 * у нас, второе нормальное состояние молодого сервиса. Слить их в одну ветку значит подсунуть
 * оператору неверный вывод о состоянии сервиса.
 */
export function deliveryNote(report: DeliveryReport | null | undefined): string {
  if (report === null) return 'Разослать сигнал не удалось — сотрудники увидят при следующем открытии экрана.'
  if (!report || report.total === 0) return 'Порталов с установленным приложением пока нет.'
  const tail = report.truncated ? ' Выборка обрезана — часть порталов сигнал не получила.' : ''
  if (!report.failed) return `Сигнал доставлен всем порталам (${report.sent}).${tail}`
  return `Сигнал доставлен ${report.sent} из ${report.total}; остальные увидят при следующем открытии экрана.${tail}`
}
