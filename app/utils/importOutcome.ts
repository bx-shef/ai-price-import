import { ON_MISSING_LABEL } from '~/config/onMissing'

// #373. Исход «ни одна позиция не перенесена» — отдельный текст, а не частный случай «часть строк
// пропущена».
//
// Живой прогон 2026-08-02: пять документов подряд дали сделки с суммой 0 и без единой товарной
// строки, и каждая была помечена «Готово». Настройка «что делать, если товар не найден» стояла в
// «пропустить», каталог портала был пуст — то есть пропускалось ВСЁ. Разница между «пропущена
// часть» и «пропущено всё» для человека принципиальная: в первом случае запись всё-таки несёт
// документ, во втором в ней нет ничего от документа вовсе.

/**
 * Предел длины строки, которую чат показывает целиком (`chatSafeText(…, MAX_CHAT_REASON)`).
 *
 * ⚠ Замер ревью: первая версия текста была 380 знаков, и в чат уезжало
 * «…Запись в CRM не создана, потому что в н» — обрыв на полуслове ровно перед обеими полезными
 * частями (что записи нет и как чинить). Сообщение об ошибке, которое не доезжает, хуже короткого,
 * поэтому длина здесь — часть контракта, а не вкусовщина. Значение продублировано намеренно
 * (`app/` не должен зависеть от `server/`); равенство сторожит тест.
 */
export const MAX_OUTCOME_TEXT = 200

/**
 * Текст жёсткой ошибки, когда пропущены ВСЕ строки документа.
 *
 * Говорит то, чего не было в прежнем предупреждении: что записи в CRM нет вовсе (иначе человек
 * пойдёт искать её в воронке) и что чинится это настройкой, а не повторной загрузкой того же файла.
 *
 * ⚠ Про поле поиска сказано раньше, чем про каталог. Этот исход по построению случается на
 * НЕнастроенном портале, где свойство артикула не задано, — значит товары в каталоге вполне могут
 * лежать, просто искали не по тому полю. Совет «заведите товары» первым уводил бы в лишнюю работу.
 */
export function allLinesSkippedError(itemCount: number): string {
  const n = Math.max(0, Math.trunc(itemCount))
  // «ни одна из 1 позиции» — сорная фраза; у документа с одной строкой она же и единственная.
  // После «ни одна из» число всегда идёт в родительном множественного («из 2 позиций»), поэтому
  // склонять по общей схеме тут нечего.
  const what = n === 1 ? 'единственная позиция' : `ни одна из ${n} позиций`
  return `Импорт остановлен: ${what} не найдена в каталоге, запись в CRM не создана. Проверьте поле поиска товара в настройках или выберите «${ON_MISSING_LABEL.freeform}».`
}

/**
 * Построчное предупреждение о пропущенной позиции — только ФАКТ, без совета.
 *
 * ⚠ Совет тут был и его убрали (живой прогон 2026-08-02). На документе из трёх позиций карточка
 * выглядела так: красная строка отказа с советом «выберите в настройках …», а под ней три
 * одинаковых абзаца с тем же советом — четыре повтора одной фразы в 45 знаков подряд. Читать это
 * невозможно, а главное — названия товаров, ради которых блок и existует, тонули в повторах.
 * Теперь строка называет товар, а совет даётся РОВНО ОДИН раз: в тексте отказа (пропущено всё)
 * либо отдельной строкой `skippedLinesAdvice` (пропущена часть).
 */
export function lineSkippedWarning(productName: string): string {
  return `Товар «${productName}» не найден в каталоге — строка пропущена.`
}

/**
 * Совет для случая «пропущена ЧАСТЬ строк» — одной строкой на весь документ.
 *
 * Нужен отдельно, потому что при частичном пропуске импорт успешен: текста отказа нет вовсе, и без
 * этой строки человек увидел бы перечень пропущенных товаров и ни слова о том, что с этим делать.
 */
export function skippedLinesAdvice(): string {
  // ⚠ Лид-ин «Что делать:» — часть ТЕКСТА, а не оформления (#388). Совет едет в три места (строка
  // задания, чат, дело таймлайна) и в каждом стоит вплотную к списку проблем; отличался он только
  // цветом полосы в 3 px — то есть в чате и деле не отличался ничем, а на экране пропадал при
  // цветовой слепоте и в чёрно-белом скриншоте. Слово впереди читается раньше цвета и переживает
  // любой клиент.
  return `Что делать: пропущенные товары можно завести в каталоге или выбрать в настройках «${ON_MISSING_LABEL.freeform}» — тогда такие строки будут вноситься как есть.`
}

/**
 * Ни одна строка не связалась с каталогом, но запись создана (`freeform` — дефолт).
 *
 * ⚠ Самый тихий из возможных исходов, и до 2026-08-05 о нём НЕ ГОВОРИЛОСЬ ничего. Импорт
 * рапортовал «Готово», сделка появлялась с полной суммой и всеми позициями, дело таймлайна шло без
 * блока «Проблемы» — а связи с номенклатурой не было ни у одной строки. Всплывает это на первом же
 * отчёте по товарам или при попытке списать остатки, то есть недели спустя и уже как расхождение
 * данных, а не как ошибка импорта.
 *
 * ⚠ Отдельный текст от `skippedLinesAdvice`: там строки ПРОПУЩЕНЫ и человек это видит по короткому
 * документу, здесь — записаны все до единой, и заметить нечего. Совет тоже другой: пропущенные
 * товары заводят в каталоге, а здесь чаще всего каталог в порядке, просто не выбрано поле артикула
 * либо в документе нет колонки с артикулом.
 *
 * ⚠ Причина названа условно, а не утвердительно («скорее всего»): со стороны воркера две ситуации
 * неразличимы — поле не выбрано или выбрано верно, но артикулов нет в самом документе. Утверждать
 * первое означало бы отправлять админа править настройку, которая может быть в порядке.
 */
export function noLinesMatchedWarning(articleFieldConfigured: boolean): string {
  const why = articleFieldConfigured
    ? 'Скорее всего, в документе нет колонки с артикулом либо артикулы поставщика не совпадают с вашими.'
    : 'Скорее всего, в настройках не выбрано поле с артикулом товара.'
  return `Ни одна позиция не связана с каталогом — все строки внесены как есть, названиями из документа. ${why}`
}
