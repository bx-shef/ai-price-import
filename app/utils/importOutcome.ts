import { pluralRu } from './jobStatus'

// #373. Исход «ни одна позиция не перенесена» — отдельный текст, а не частный случай «часть строк
// пропущена».
//
// Живой прогон 2026-08-02: пять документов подряд дали сделки с суммой 0 и без единой товарной
// строки, и каждая была помечена «Готово». Настройка «Если товар не найден» стояла в «пропустить»,
// каталог портала был пуст — то есть пропускалось ВСЁ. Разница между «пропущена часть» и
// «пропущено всё» для человека принципиальная: в первом случае запись всё-таки несёт документ,
// во втором в ней нет ничего от документа вовсе.

/**
 * Текст жёсткой ошибки, когда пропущены ВСЕ строки документа.
 *
 * Говорит три вещи, которых не было в прежнем предупреждении: что не перенесено НИЧЕГО, что запись
 * поэтому не создана (иначе человек пойдёт искать её в воронке), и что чинится это настройкой, а не
 * повторной загрузкой того же файла.
 */
export function allLinesSkippedError(itemCount: number): string {
  const n = Math.max(0, Math.trunc(itemCount))
  const what = `${n} ${pluralRu(n, ['позиция', 'позиции', 'позиций'])}`
  return `Импорт остановлен: ни одна позиция не перенесена — ни один из товаров документа (${what}) не найден в каталоге Битрикс24, а в настройках выбрано «пропустить». Запись в CRM не создана, потому что в ней не было бы ни одной строки. Заведите товары в каталоге или поменяйте в настройках импорта «Если товар не найден» на «Внести как произвольную позицию» и загрузите документ снова.`
}
