import { ON_MISSING_LABEL } from '~/config/onMissing'

// #373. Исход «ни одна позиция не перенесена» — отдельный текст, а не частный случай «часть строк
// пропущена».
//
// Живой прогон 2026-08-02: пять документов подряд дали сделки с суммой 0 и без единой товарной
// строки, и каждая была помечена «Готово». Настройка «что делать, если товар не найден» стояла в
// «пропустить», каталог портала был пуст — то есть пропускалось ВСЁ. Разница между «пропущена
// часть» и «пропущено всё» для человека принципиальная: в первом случае запись всё-таки несёт
// документ, во втором в ней нет ничего от документа вовсе.

/**
 * Предел длины строки, которую чат показывает целиком (`chatSafeText(…, MAX_CHAT_REASON)`).
 *
 * ⚠ Замер ревью: первая версия текста была 380 знаков, и в чат уезжало
 * «…Запись в CRM не создана, потому что в н» — обрыв на полуслове ровно перед обеими полезными
 * частями (что записи нет и как чинить). Сообщение об ошибке, которое не доезжает, хуже короткого,
 * поэтому длина здесь — часть контракта, а не вкусовщина. Значение продублировано намеренно
 * (`app/` не должен зависеть от `server/`); равенство сторожит тест.
 */
export const MAX_OUTCOME_TEXT = 200

/**
 * Текст жёсткой ошибки, когда пропущены ВСЕ строки документа.
 *
 * Говорит то, чего не было в прежнем предупреждении: что записи в CRM нет вовсе (иначе человек
 * пойдёт искать её в воронке) и что чинится это настройкой, а не повторной загрузкой того же файла.
 *
 * ⚠ Про поле поиска сказано раньше, чем про каталог. Этот исход по построению случается на
 * НЕнастроенном портале, где свойство артикула не задано, — значит товары в каталоге вполне могут
 * лежать, просто искали не по тому полю. Совет «заведите товары» первым уводил бы в лишнюю работу.
 */
export function allLinesSkippedError(itemCount: number): string {
  const n = Math.max(0, Math.trunc(itemCount))
  // «ни одна из 1 позиции» — сорная фраза; у документа с одной строкой она же и единственная.
  // После «ни одна из» число всегда идёт в родительном множественного («из 2 позиций»), поэтому
  // склонять по общей схеме тут нечего.
  const what = n === 1 ? 'единственная позиция' : `ни одна из ${n} позиций`
  return `Импорт остановлен: ${what} не найдена в каталоге, запись в CRM не создана. Проверьте поле поиска товара в настройках или выберите «${ON_MISSING_LABEL.freeform}».`
}

/**
 * Построчное предупреждение о пропущенной позиции.
 *
 * Живёт здесь ради одного: цитировать пункт настроек из общего источника. Прежний текст звал его
 * «Внести как произвольную позицию» — пункта с таким названием в интерфейсе нет.
 */
export function lineSkippedWarning(productName: string): string {
  return `Товар «${productName}» не найден в каталоге — строка пропущена. Заведите товар или выберите в настройках «${ON_MISSING_LABEL.freeform}».`
}
