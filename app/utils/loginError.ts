// Ответ сервера входа → текст для оператора (#271-M). Раньше любой отказ схлопывался в «Не удалось
// войти», и три очень разные ситуации выглядели одинаково: неверный пароль, вход выключен и
// сработавшая защита от перебора. Последняя особенно обидна — человек продолжает набирать пароль,
// хотя сервер его сейчас всё равно не примет, и каждой попыткой продлевает себе окно ожидания.
//
// Чистая функция, без ввода-вывода: сопоставление статуса и текста проверяется тестом.

/** Через сколько секунд можно повторить (из заголовка `Retry-After`). */
function retryHint(retryAfterSec?: number | null): string {
  if (!retryAfterSec || !Number.isFinite(retryAfterSec) || retryAfterSec <= 0) return ''
  const minutes = Math.ceil(retryAfterSec / 60)
  return minutes <= 1 ? ' Попробуйте через минуту.' : ` Попробуйте через ${minutes} мин.`
}

export interface LoginFailure {
  /** HTTP-статус ответа. */
  status?: number
  /** Текст ошибки от сервера, если он был. */
  serverMessage?: string
  /** Значение заголовка `Retry-After` в секундах (только у 429). */
  retryAfterSec?: number | null
}

/**
 * Текст под формой входа. Статус важнее текста сервера: сообщение может измениться, а смысл кода —
 * нет. Ответ сервера берём только там, где он несёт что-то сверх кода.
 */
export function loginErrorMessage(f: LoginFailure): string {
  switch (f.status) {
    case 401:
      return 'Неверный пароль.'
    case 429:
      return `Слишком много попыток входа.${retryHint(f.retryAfterSec) || ' Подождите и попробуйте снова.'}`
    case 503:
      return 'Вход оператора отключён администратором.'
    default:
      // Сеть недоступна, прокси отдал 502 и прочее «не наше» — не выдумываем причину.
      return f.serverMessage?.trim() || 'Не удалось войти. Проверьте соединение и попробуйте снова.'
  }
}

/** Заблокирован ли вход прямо сейчас — форму в этом состоянии держим неактивной. */
export function isLockedOut(status?: number): boolean {
  return status === 429
}
