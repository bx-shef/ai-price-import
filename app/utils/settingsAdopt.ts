// Что делать с ВЫБРАННОЙ ЦЕЛЬЮ вкладки, когда пришло событие «настройки изменились» (#443).
//
// Событие широковещательное: админ поменял настройки — оно прилетает ВСЕМ сотрудникам портала, в
// браузеры и в мобильные приложения. У каждого из них на экране может быть свой выбор направления,
// запомненный на вкладку (#349), и вопрос «кто побеждает» решается здесь, а не порядком вызовов.
//
// ⚠ Решение владельца 09.08.2026: **побеждает настройка портала**. Память вкладки заводилась ради
// удобства («не выбирать направление на каждую пачку»), а не ради того, чтобы пережить смену
// настройки: админ сменил цель именно затем, чтобы документы шли туда, и вкладка, тихо продолжающая
// слать по-старому, — ровно тот случай, когда «удобство» работает против человека.
//
// ⚠⚠ РОВНО ОДИН СПОСОБ ЭТО СДЕЛАТЬ — СБРОСИТЬ НА «АВТО», а НЕ подставить `defaultTarget`.
// Первая редакция подставляла цель по умолчанию, и это переворачивало механизм маршрутизации у
// всего портала одним нажатием (разбор параллельной сессии, PR #476 — там же и найдено):
//   • цель по умолчанию ВСЕГДА конкретна — `parsePortalSettings` подставляет `FALLBACK_TARGET`,
//     то есть `null` оттуда не приходит никогда;
//   • попав в пикер, она уезжает с файлом и на сервере становится `manualOverride`;
//   • а `manualOverride` в `resolveTarget` бьёт ПЕРВЫМ приоритетом — ВЫШЕ правил маршрутизации.
// Значит админ, поправивший что угодно — хоть синоним единицы измерения, — тем же нажатием
// выключал бы собственные правила «какие документы куда вносить» у каждого открытого экрана.
// Молча и почти у всех: «Авто» это состояние по умолчанию.
//   `null` не кладёт поле цели в задание вовсе, сервер идёт правила → цель по умолчанию, то есть
// ровно «как настроил админ». Итог для человека тот же (правил нет ⇒ применится та же цель), но
// механизм не подменён.

/**
 * Исход решения.
 *
 * `apply: false` — сейчас не применяем; `reason` только для журнала и тестов, в интерфейс не идёт.
 * `apply: true` — сбросить выбор вкладки на «Авто (по правилам)», память очищается.
 */
export type AdoptDecision
  = | { apply: false, reason: 'importing' }
    | { apply: true }

export interface AdoptInput {
  /** Пачка прямо сейчас грузится. */
  importing: boolean
}

/**
 * Decide what happens to the tab's chosen target when settings change portal-wide.
 *
 * ⚠ **Идущая пачка не затрагивается — и это обязательное, а не желательное.** Задания уже приняты
 * сервером, и их поведение определяется настройками НА МОМЕНТ ПОСТАНОВКИ. Подменить цель в
 * интерфейсе посреди пачки значило бы показать человеку не то, куда на самом деле уедут его
 * документы, — соврать ровно про то, ради чего он на этот экран и смотрит.
 *
 * ⚠ Отказ здесь — ОТСРОЧКА, а не отмена: вызывающий обязан запомнить событие и применить его на
 * спаде пачки. Прежняя редакция выбрасывала правку насовсем, и рассылку терял ровно тот сотрудник,
 * ради которого её делали, — он же единственный, кто в этот момент работает.
 */
export function adoptDefaultTarget(input: AdoptInput): AdoptDecision {
  if (input.importing) return { apply: false, reason: 'importing' }
  return { apply: true }
}
