import type { TargetRef } from '~/types/mapping'

// Что делать с ВЫБРАННОЙ ЦЕЛЬЮ вкладки, когда пришло событие «настройки изменились» (#443).
//
// Событие широковещательное: админ поменял настройки — оно прилетает ВСЕМ сотрудникам портала, в
// браузеры и в мобильные приложения. У каждого из них на экране может быть свой выбор направления,
// запомненный на вкладку (#349), и вопрос «кто побеждает» решается здесь, а не порядком вызовов.
//
// ⚠ Решение владельца 09.08.2026: **побеждает новое значение из настроек**. Память вкладки
// заводилась ради удобства («не выбирать направление на каждую пачку»), а не ради того, чтобы
// пережить смену настройки портала: админ сменил цель по умолчанию именно затем, чтобы документы
// шли туда, и вкладка, тихо продолжающая слать по-старому, — это ровно тот случай, когда «удобство»
// работает против человека.
//
// ⚠ «Авто (по правилам)» — ТОЖЕ значение, а не отсутствие значения: если админ вернул цель по
// умолчанию в «Авто», память обязана очиститься. Иначе настройку невозможно откатить — прежний
// выбор пережил бы любое изменение, и это выглядело бы как «настройки не применяются».

/**
 * Исход решения.
 *
 * `apply: false` — ничего не трогаем; `reason` только для журнала и тестов, в интерфейс не идёт.
 * `apply: true` — применить; `target === null` означает «Авто (по правилам)», память очищается.
 */
export type AdoptDecision
  = | { apply: false, reason: 'importing' }
    | { apply: true, target: TargetRef | null }

export interface AdoptInput {
  /** Пачка прямо сейчас грузится. */
  importing: boolean
  /** Цель по умолчанию из ТОЛЬКО ЧТО прочитанных настроек; `null` — «Авто (по правилам)». */
  defaultTarget: TargetRef | null | undefined
}

/**
 * Decide what happens to the tab's chosen target when settings change portal-wide.
 *
 * ⚠ **Идущая пачка не затрагивается — и это обязательное, а не желательное.** Задания уже приняты
 * сервером, и их поведение определяется настройками НА МОМЕНТ ПОСТАНОВКИ: сервер прочитал их, когда
 * ставил задачу, и событие в браузере на это повлиять не может. Подменить цель в интерфейсе посреди
 * пачки значило бы показать человеку не то, куда на самом деле уедут его документы, — то есть
 * соврать ровно про то, ради чего он на этот экран и смотрит. Оставшиеся файлы пачки при этом тоже
 * идут со старой целью: цель одна на пачку и заморожена на время прогона (#349).
 */
export function adoptDefaultTarget(input: AdoptInput): AdoptDecision {
  if (input.importing) return { apply: false, reason: 'importing' }
  const t = input.defaultTarget
  // ⚠ Негодная цель читается как «Авто», а не игнорируется: настройки приходят с сервера уже
  // нормализованными, но признак «цель задана» — это положительный тип сущности, и молча оставить
  // прежний выбор при мусоре значило бы залипнуть на нём навсегда.
  return { apply: true, target: t && t.entityTypeId > 0 ? t : null }
}
