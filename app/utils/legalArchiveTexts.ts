// Тексты архивных редакций (#415). ОТДЕЛЬНЫЙ модуль, и это не вкусовщина.
//
// ⚠ `import.meta.glob` нельзя класть в `app/utils/legalArchive.ts`: тот модуль читают
// `nuxt.config.ts` (через jiti) и `server/utils/seoFiles.ts` (через Nitro), а `import.meta.glob` —
// конструкция клиентского сборщика, и в обоих этих контекстах она уронит сборку. Реестр и тексты
// живут врозь именно поэтому.
//
// ⚠ `eager: false`. С `eager: true` страница ОДНОЙ редакции тянула бы в свой чанк тексты ВСЕХ
// редакций всех четырёх документов: сегодня это 4 файла, через пять лет — двадцать, и каждый
// посетитель качал бы их целиком ради одного. Текст редакции и так уже лежит в пререндеренном
// HTML, так что второй экземпляр в JS — чистая трата.

const texts = import.meta.glob('~~/docs/archive/**/*.md', { query: '?raw', import: 'default' }) as Record<string, () => Promise<string>>

/**
 * Текст редакции или `''`, если такого снимка нет.
 *
 * Ключи глоба — пути вида `/docs/archive/<документ>/<дата>.md`, поэтому сравниваем по хвосту:
 * префикс зависит от сборщика, а хвост — наш и стабильный. Путь из аргументов НЕ склеивается —
 * ищем среди заранее известных ключей, поэтому «..» и прочая хитрость в адресе никуда не ведут.
 */
export async function loadEditionText(slug: string, date: string): Promise<string> {
  const tail = `/${slug}/${date}.md`
  const hit = Object.entries(texts).find(([path]) => path.endsWith(tail))
  return hit ? await hit[1]() : ''
}
