// Состояние загрузки экрана внутри портала (#408, продолжение #256).
//
// Дефект, который это чинит: экран УТВЕРЖДАЕТ то, чего ещё не знает. Метрики рисуют нули, и человек
// читает «0 документов» как факт о своём портале — а при нулях срабатывает ещё и ветка пустого
// состояния, то есть портал, где импорт шёл месяцами, на долю секунды сообщает, что импортов не
// было. Настройки рисуют форму со значениями по умолчанию, которые на глазах подменяются
// сохранёнными: на медленной сети это читается как сброс настроек — худшая из возможных трактовок
// для экрана, где лежит конфигурация записи в CRM.
//
// Здесь — только правило. Ни DOM, ни запросов.

/** Что показывать экрану прямо сейчас. */
export type ScreenState = 'loading' | 'error' | 'ready'

export interface ScreenStateInput {
  /** Первая попытка загрузки ЗАВЕРШИЛАСЬ (успехом или отказом). */
  loaded: boolean
  /** Текст ошибки загрузки. Пусто — ошибки нет. */
  error?: string | null
  /**
   * Экран работоспособен и без серверных данных.
   *
   * ⚠ Нужно для страниц вне портала: там фрейм-токена нет, загрузка не начнётся никогда, и без
   * этого флага человек остался бы наедине с вечным скелетоном. Предпросмотр — не отказ.
   */
  inert?: boolean
}

/**
 * Три исхода, а не два.
 *
 * ⚠ Порядок проверок важен. `loaded` идёт ПЕРВЫМ: пока первая попытка не завершилась, никакая
 * ошибка ещё не могла возникнуть, а прошлая — уже неактуальна. Обратный порядок показывал бы
 * ошибку предыдущей попытки поверх идущей загрузки.
 *
 * ⚠ Отказ — отдельный исход, а не вечный скелетон: «грузится» и «не загрузилось» человек различить
 * обязан, иначе он ждёт бесконечно.
 *
 * ⚠ `inert` стоит ПЕРВЫМ и перебивает даже ошибку: вне портала запроса не было, значит и отказа
 * быть не могло — показывать его там значило бы объяснять несуществующую поломку.
 */
export function screenState(input: ScreenStateInput): ScreenState {
  if (input.inert) return 'ready'
  if (!input.loaded) return 'loading'
  if (input.error) return 'error'
  return 'ready'
}
