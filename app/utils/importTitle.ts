// Заголовок создаваемой записи CRM (#440). Чистая функция — здесь она достижима тестом, а в
// `crmSyncCore` собиралась строкой на месте.
//
// ⚠ Почему название поставщика попадает в заголовок НЕ ВСЕГДА. Заголовок — не предупреждение,
// которое прочитали и забыли: он становится ИМЕНЕМ ЗАПИСИ В CRM КЛИЕНТА НАВСЕГДА, попадает в
// списки, поиск и отчёты, и через месяц никто не помнит, что это распознанный текст, а не
// введённый человеком. Поэтому туда идёт только то, чему есть основание доверять.
//
// ⚠ Признак доверия — НАЛИЧИЕ НАЛОГОВОГО НОМЕРА, и это не формальность: УНП/ИНН/БИН стоит в той же
// шапке, что и название. Не найдя номер, модель, скорее всего, не разобрала и шапку — значит рядом
// стоящее название прочитано криво. Наоборот не работает: номер распознан, а компании с ним в CRM
// нет — это НЕ ошибка чтения, а новый контрагент; шапка прочитана, название почти наверняка верное,
// и оно единственная зацепка для менеджера. Поэтому правило смотрит на номер, а не на то, нашлась
// ли компания.

import type { ExtractedDocument } from '~/types/document'

/** Запасной заголовок, когда о документе не известно даже типа. */
const FALLBACK = 'документ'

/**
 * Заголовок записи: «Импорт: <название>» либо, при нераспознанном номере, «Импорт: <тип> на <сумма>».
 *
 * ⚠ Запасной вариант НЕ «Импорт: документ»: в списке из полусотни сделок такие строки неразличимы,
 * и человек не понимает, какую открывать. Тип документа и сумма взяты из самого документа — их
 * видно глазами на бумаге, они проверяемы и моделью не выдуманы в том смысле, в каком выдумано
 * может быть название.
 */
export function buildImportTitle(doc: Pick<ExtractedDocument, 'supplier' | 'documentType' | 'total' | 'currency'>): string {
  const trusted = supplierNameTrusted(doc)
  if (trusted) return `Импорт: ${trusted}`.slice(0, 255)
  const kind = (doc.documentType ?? '').trim() || FALLBACK
  const amount = formatDocTotal(doc.total, doc.currency)
  return `Импорт: ${amount ? `${kind} на ${amount}` : kind}`.slice(0, 255)
}

/**
 * Название поставщика, которому есть основание доверять, либо `null`.
 *
 * Отдельная функция, а не флаг внутри заголовка: то же правило нужно полю `companyTitle` лида, а
 * два независимых условия разъехались бы — и тогда имя, не попавшее в заголовок, всё равно
 * оказалось бы в карточке, причём уже как ДАННЫЕ, а не как подпись.
 */
export function supplierNameTrusted(doc: Pick<ExtractedDocument, 'supplier'>): string | null {
  const name = (doc.supplier?.name ?? '').trim()
  const taxId = (doc.supplier?.taxId ?? '').trim()
  if (!name || !taxId) return null
  return name
}

/** Сумма документа «10 320,00 BYN». Нет суммы или она не число — `null`, часть заголовка опускается. */
function formatDocTotal(total: number | undefined | null, currency: string | undefined | null): string | null {
  if (total == null || !Number.isFinite(total)) return null
  const shown = total.toLocaleString('ru-RU', { minimumFractionDigits: 2, maximumFractionDigits: 2 })
  const cur = (currency ?? '').trim()
  return cur ? `${shown} ${cur}` : shown
}
