// Издание юридического документа — дата редакции и дата вступления её в силу (#414).
//
// Зачем парсер, а не константа. Запись о согласии обязана назвать РЕДАКЦИИ, с которыми согласились
// (иначе она доказывает только «когда-то нажали галочку», а спор всегда про то, ЧТО именно человек
// принял). Дата живёт в самом документе, в двух строках под заголовком, — и это единственное место,
// где её правят. Константа рядом стала бы второй копией и разошлась бы с текстом ровно на той
// правке, ради которой согласие и берут заново.
//
// ⚠ Формат не «какой получилось», а тот, который уже требует `tests/docsStructure.test.ts` от всех
// четырёх опубликованных документов: `**Редакция от:** ДД.ММ.ГГГГ`. Парсер и гард смотрят на одну
// и ту же строку с разных сторон, поэтому документ без даты не доедет ни до страницы, ни до записи.

export interface LegalEdition {
  /** Дата редакции, как она напечатана в документе: `ДД.ММ.ГГГГ`. */
  edition: string
  /** Дата вступления этой редакции в силу, `ДД.ММ.ГГГГ`. */
  effective: string
}

const EDITION_RE = /\*\*Редакция от:\*\*\s*(\d{2}\.\d{2}\.\d{4})/
const EFFECTIVE_RE = /\*\*Дата вступления редакции в силу:\*\*\s*(\d{2}\.\d{2}\.\d{4})/

/**
 * Достать издание из текста документа.
 *
 * ⚠ Бросает, а не возвращает `null`: обе даты обязательны по гарду документов, поэтому их
 * отсутствие — это не «данных нет», а сломанный документ. Молчаливый `null` уехал бы в запись о
 * согласии пустой строкой, и доказательство превратилось бы в «принял неизвестно что» — ровно то,
 * ради чего эта запись существует. Падение видно на сборке (модуль читается на импорте).
 */
export function parseLegalEdition(source: string, what = 'документ'): LegalEdition {
  const edition = EDITION_RE.exec(source)?.[1]
  const effective = EFFECTIVE_RE.exec(source)?.[1]
  if (!edition || !effective) {
    throw new Error(`[legalEdition] ${what}: не найдена дата редакции или дата вступления в силу`)
  }
  return { edition, effective }
}
