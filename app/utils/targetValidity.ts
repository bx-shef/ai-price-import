// Годен ли ВЫБРАННЫЙ сотрудником маршрут импорта (#488, решение владельца 09.08.2026).
//
// ЗАЧЕМ ЭТО ОТДЕЛЬНОЕ ПРАВИЛО. Выбор «Куда» принадлежит сотруднику: правила маршрутизации, которые
// задаёт админ, применяются ТОЛЬКО к тем, у кого стоит «Авто» — в этом весь смысл «Авто». Значит
// чужое сохранение настроек не вправе трогать выбранную цель, и единственная законная причина её
// сменить — цель перестала существовать: сущность отключили, направление или стадию удалили в CRM.
//
// ⚠ И тогда смена ОБЪЯВЛЯЕТСЯ. Молчаливая подмена запрещена: человек видит в пикере другое значение
// и не знает, почему — а следующая пачка уходит не туда, куда он рассчитывал. Прежде направление и
// стадия дочищались тихо, и это ровно тот случай.

/** Что именно у выбранного маршрута перестало существовать. */
export type TargetInvalidReason = 'entity' | 'category' | 'stage'

/** Что предъявляет портал СЕЙЧАС. `undefined` — «ещё не загружено», а не «пусто». */
export interface PortalChoices {
  /** Типы сущностей, доступные на портале (из пикера: лид/сделка/смарт-счёт/смарт-процессы). */
  entityIds: number[] | undefined
  /** Направления выбранного типа. `[]` — у типа их не бывает (лид), это НЕ ошибка. */
  categoryIds: number[] | undefined
  /** Стадии выбранного направления. */
  stageIds: string[] | undefined
}

/** Что выбрано на вкладке. `entityTypeId: null` — «Авто», проверять нечего. */
export interface ChosenTarget {
  entityTypeId: number | null
  categoryId?: number
  stageId?: string
}

/**
 * Check the chosen import target against what the portal currently offers.
 *
 * ⚠ **Незагруженное (`undefined`) НИКОГДА не читается как «не существует»** — иначе на медленной
 * сети экран объявлял бы негодным исправный маршрут и уводил человека в «Авто» на ровном месте.
 * Это самая дорогая ошибка в этой функции: она несимметрична, ложная тревога хуже задержки.
 *
 * ⚠ Пустой список направлений — законное состояние (у лида их нет вовсе), поэтому негодным делает
 * не пустота списка, а ОТСУТСТВИЕ выбранного значения в загруженном списке.
 */
export function targetInvalidReason(chosen: ChosenTarget, portal: PortalChoices): TargetInvalidReason | null {
  const etid = chosen.entityTypeId
  if (etid == null) return null // «Авто» — проверять нечего
  if (portal.entityIds && !portal.entityIds.includes(etid)) return 'entity'
  if (chosen.categoryId != null && portal.categoryIds && !portal.categoryIds.includes(chosen.categoryId)) return 'category'
  if (chosen.stageId != null && portal.stageIds && !portal.stageIds.includes(chosen.stageId)) return 'stage'
  return null
}

/** Что именно пропало — половина сообщения, одинаковая на обоих экранах. */
const LOST: Record<TargetInvalidReason, string> = {
  entity: 'Выбранный тип записи больше не доступен в вашей CRM.',
  category: 'Направление, выбранное для импорта, удалено в CRM.',
  stage: 'Стадия, выбранная для импорта, удалена в CRM.'
}

/**
 * Текст для человека. Говорит ЧТО пропало и ЧТО теперь будет — иначе сообщение сводится к «что-то
 * пошло не так», после которого следующее действие неизвестно.
 *
 * ⚠ Вторая половина РАЗНАЯ у двух экранов, и это не украшательство. На экране импорта выбор
 * действительно уходит в «Авто», а в настройках цель сохраняется (#492) — там «переключён на Авто»
 * было бы прямой неправдой о том, что сейчас записано в правиле. Раньше текст был один на оба
 * экрана и в настройках врал.
 */
export function targetInvalidMessage(reason: TargetInvalidReason, switchedToAuto: boolean): string {
  return switchedToAuto
    ? `${LOST[reason]} Импорт переключён на «Авто (по правилам)» — выберите цель заново.`
    : `${LOST[reason]} Выберите другую цель и сохраните настройки.`
}
