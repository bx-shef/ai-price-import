// Склейка одновременных загрузок и защита от ответа-опоздавшего (#480).
//
// ЗАЧЕМ. Рассылка настроек (#443) уходит в ОБЩИЙ канал портала и будит КАЖДЫЙ открытый экран
// импорта. Каждый идёт в `GET /api/settings`, а тот стоит трёх обращений к Битрикс24 — проверка
// фрейм-токена, чтение настроек и базовая валюта. На портале с полусотней открытых вкладок одно
// нажатие «Сохранить» давало около полутора сотен одновременных запросов, и часть сотрудников
// получала `QUERY_LIMIT_EXCEEDED`. Внешне это выглядит как «у некоторых не применилось», причём
// молча: неудачная загрузка настроек после #476 ничего не ломает и ничего не говорит.
//
// ⚠ Дефект ВИДЕН ТОЛЬКО НА МАСШТАБЕ. На тест-портале с одной вкладкой ни веера, ни гонки не бывает
// по построению, поэтому правило и вынесено сюда: его можно проверить тестом, а не глазами.

/**
 * Один полёт на всех, и ОДИН ХВОСТОВОЙ повтор.
 *
 * ⚠ Голая склейка «пока запрос в воздухе — присоединяйся» здесь НЕВЕРНА, и это не мелочь. Запрос,
 * начатый ДО сохранения, вернёт настройки ДО сохранения. Присоединив к нему того, кто пришёл ПОСЛЕ
 * (а приходят сюда именно по событию «настройки изменились»), мы бы отдали ему заведомо устаревший
 * ответ и на этом успокоились — то есть починили бы расход ценой правильности, ровно в том месте,
 * ради которого весь механизм и существует.
 *
 * Поэтому: пока полёт идёт, пришедшие ЗАПОМИНАЮТСЯ одним флагом, и по завершении делается РОВНО ОДИН
 * повтор — сколько бы их ни пришло. На вкладку выходит не больше двух запросов вместо N, и последний
 * гарантированно начат позже последнего события.
 *
 * ⚠ Обещание сбрасывается в `finally`, а не в `then`: после отказа следующий вызов обязан пойти в
 * сеть заново, иначе один сетевой сбой запирал бы экран на отказе навсегда.
 */
export function createSingleFlight(): { run: (task: () => Promise<void>) => Promise<void>, inFlight: () => boolean } {
  let pending: Promise<void> | null = null
  let queued = false

  function start(task: () => Promise<void>): Promise<void> {
    const p = (async () => {
      try {
        await task()
      } finally {
        pending = null
      }
      if (queued) {
        queued = false
        await start(task)
      }
    })()
    pending = p
    return p
  }

  return {
    run(task: () => Promise<void>): Promise<void> {
      if (pending) {
        queued = true
        return pending
      }
      return start(task)
    },
    inFlight: () => pending !== null
  }
}

/**
 * Задержка перед перечитыванием после ШИРОКОВЕЩАТЕЛЬНОГО события.
 *
 * ⚠ Разброс обязателен, потому что момент выбирает не сотрудник, а админ: сигнал получают ВСЕ
 * вкладки ВСЕХ сотрудников одновременно, и без разброса штатное сохранение настроек само себе
 * устраивает всплеск на самом дорогом пути ровно в одну секунду. Правка настроек — событие редкое,
 * секунда-другая задержки не стоит ничего; всплеск стоит отказов у части людей.
 *
 * ⚠ Свой вызов (открыли экран, нажали «Обновить») задержки НЕ получает — там момент выбрал человек,
 * и ждать его заставлять незачем. Разброс касается только реакции на чужое сохранение.
 */
export const SETTINGS_RELOAD_JITTER_MS = 4000

/** Случайная задержка в пределах разброса. Отдельная функция — чтобы тест мог подменить источник. */
export function reloadDelayMs(random: () => number = Math.random): number {
  const r = random()
  const safe = Number.isFinite(r) && r >= 0 && r < 1 ? r : 0
  return Math.floor(safe * SETTINGS_RELOAD_JITTER_MS)
}
