// Защита живых проверок от запуска на БОЕВОМ портале клиента.
//
// ⚠ Заведена по следам разбора: скрипты `verify:*` создают чат и пишут в него, а чат в Bitrix24
// по REST **не удаляется** — на портале клиента навсегда остался бы мусорный чат с техническим
// названием. Хуже того, `verify:legal` шлёт сообщение, выглядящее как настоящее уведомление об
// изменении лицензии: с реальной датой редакции, рабочей ссылкой на архив и фразой «удалить с
// портала до … без последствий».
//
// ⚠ Единственной «защитой» был префикс `[TEST]` в НАЗВАНИИ чата — то есть косметика: на скриншоте,
// в пересылке и в уведомлении на телефоне видно текст сообщения, а не название чата.
//
// ⚠ Путаница адресов здесь не гипотетическая, а уже случившаяся: в оболочке живёт `B24_HOOK`
// прежнего портала, и именно поэтому скрипты читают файл раньше переменной. Ровно этот сценарий —
// «в переменной чужой адрес» — и приводит на боевой портал.

/** Домены, на которых разрешено проводить живые проверки. */
const ALLOWED = new Set([
  'b24-hrbvzq.bitrix24.by' // тест-портал проекта
])

/**
 * Разрешить проверку на этом портале или остановиться.
 *
 * Осознанный запуск на другом портале возможен — но только явным согласием, где домен назван
 * руками: `--yes-target=<домен>`. Молчаливого «наверное, это тестовый» здесь нет by design.
 */
export function assertTestPortal(hookUrl, argv = process.argv) {
  let host
  try {
    host = new URL(hookUrl).host.toLowerCase()
  } catch {
    console.error('не разобрать адрес вебхука')
    process.exit(1)
  }
  if (ALLOWED.has(host)) return host

  const consent = argv.find(a => a.startsWith('--yes-target='))
  if (consent && consent.slice('--yes-target='.length).trim().toLowerCase() === host) {
    console.warn(`⚠ портал ${host} не в списке тестовых — продолжаю по явному согласию (--yes-target)`)
    return host
  }

  console.error(
    `\n⛔ Отказ: ${host} не входит в список тестовых порталов.\n`
    + '   Живые проверки создают чат (он НЕ удаляется по REST) и пишут в него сообщения,\n'
    + '   в том числе похожие на официальные уведомления. На боевом портале это мусор,\n'
    + '   который нельзя убрать.\n\n'
    + `   Если вы уверены — повторите с явным согласием: --yes-target=${host}\n`
  )
  process.exit(1)
}
