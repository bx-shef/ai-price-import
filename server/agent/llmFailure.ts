// Отказы сервиса распознавания: класс → текст для человека (#416). Чистое ядро, без I/O.
//
// П. 8.4 EULA обещает, что приложение сообщает об отказах в чат Портала. Механически это уже
// работало: `runChatExtract` не бросает, возвращает `{ok:false, error}`, а `failJob` доводит причину
// до сотрудника и в чат ошибок. Проблема была в СОДЕРЖАНИИ причины — до сотрудника доезжала строка
// провайдера как есть:
//
//   • она ничего не объясняет («429 Too Many Requests» не говорит, надо ли повторять и когда);
//   • и её опасно показывать: тело ответа провайдера вправе процитировать присланный запрос, а в
//     запросе лежит текст документа клиента. Пересылать это в чужой рабочий чат нельзя.
//
// Поэтому наружу уходит ТОЛЬКО текст, написанный здесь, а исходная строка не покидает журнал — и
// даже туда идёт просеянной (см. `llmErrorSignature`).

/** Классы отказа, различимые по смыслу для того, кто загрузил документ. */
export type LlmFailureKind
  = | 'quota' // лимит/квота исчерпаны
    | 'auth' // ключ отвергнут или не задан
    | 'unavailable' // провайдер недоступен (5xx, сеть, таймаут)
    | 'too-long' // документ не помещается в контекст модели
    | 'unparsable' // ответ пришёл, но разобрать его не удалось
    | 'unknown' // ни один признак не сработал

// ⚠ Порядок проверок значим, а не косметичен: «429 insufficient_quota» это одновременно и лимит, и
// 4xx. Квота идёт первой, потому что для человека это другой совет («позже» против «позовите
// издателя»). Сеть/5xx — последними, чтобы не перехватывать 400-е с числом в тексте.
const PATTERNS: Array<[LlmFailureKind, RegExp]> = [
  ['quota', /quota|insufficient_quota|billing|\b429\b|rate.?limit|too many requests|лимит/i],
  ['auth', /missing api key|not configured|invalid.?api.?key|unauthor|forbidden|\b401\b|\b403\b|authentication/i],
  ['too-long', /context.?length|maximum context|too many tokens|context_length_exceeded|token limit|слишком длин/i],
  ['unparsable', /не извлёк|не удалось разобрать|invalid json|unexpected token|json/i],
  ['unavailable', /\b5\d\d\b|overloaded|gateway|unavailable|ECONNRESET|ETIMEDOUT|ENOTFOUND|EAI_AGAIN|socket hang up|timed? ?out|network/i]
]

/**
 * Класс отказа по строке ошибки.
 *
 * ⚠ Классификация по тексту сообщения — сознательный компромисс, тот же, что у `classifyAgentError`:
 * у OpenAI-совместимого транспорта разные провайдеры кладут код то в статус, то в тело, и единого
 * машинного признака нет. Неузнанное — `unknown`, а не «сеть»: выдуманный диагноз хуже честного
 * «причина не определена», потому что он уводит человека чинить не то.
 */
export function classifyLlmFailure(raw: string | undefined): LlmFailureKind {
  const m = String(raw ?? '')
  if (!m.trim()) return 'unknown'
  for (const [kind, re] of PATTERNS) if (re.test(m)) return kind
  return 'unknown'
}

/**
 * Все классы отказа списком.
 *
 * ⚠ Выведен ИЗ карты текстов, а не написан рядом с ней: вторая рукописная копия молча разошлась бы
 * с типом, и живая проверка перестала бы покрывать новый класс, оставаясь зелёной.
 */
export const LLM_FAILURE_KINDS: LlmFailureKind[] = ['quota', 'auth', 'unavailable', 'too-long', 'unparsable', 'unknown']

// Тексты. Каждый отвечает на три вопроса: что случилось, что делать, будет ли повтор.
//
// ⚠ Ни один НЕ обещает автоматического повтора — его нет: отказ извлечения терминальный, задание
// закрывается, очереди отложенных повторов в проекте намеренно не заведено (решение владельца).
// Обещание «попробуем сами позже» заставило бы человека ждать того, чего не произойдёт.
// ⚠ И ни один не обвиняет клиента в том, что от него не зависит: квота, ключ и доступность —
// наша сторона, и это сказано прямо.
const MESSAGES: Record<LlmFailureKind, string> = {
  'quota': 'Исчерпан лимит обращений к сервису распознавания на стороне приложения. Документ не обработан. Попробуйте позже — автоматического повтора нет.',
  'auth': 'Сервис распознавания отклонил доступ приложения: ключ недействителен. Это неполадка на нашей стороне — сообщите издателю приложения. Документ не обработан.',
  'unavailable': 'Сервис распознавания временно недоступен. Документ не обработан. Загрузите его снова через несколько минут — автоматического повтора нет.',
  'too-long': 'Документ слишком длинный для распознавания. Разделите его на части и загрузите по отдельности.',
  'unparsable': 'Не удалось разобрать ответ сервиса распознавания: табличная часть не извлечена. Попробуйте загрузить документ ещё раз или проверьте, что таблица в нём читается.',
  'unknown': 'Не удалось распознать документ: причина не определена. Подробности записаны в журнал приложения. Попробуйте позже — автоматического повтора нет.'
}

/** Проверка: список классов не разошёлся с картой текстов. */
if (LLM_FAILURE_KINDS.length !== Object.keys(MESSAGES).length) {
  throw new Error('LLM_FAILURE_KINDS разошёлся с картой текстов отказа')
}

/** Текст отказа для сотрудника. Единственное, что уходит наружу. */
export function llmFailureMessage(kind: LlmFailureKind): string {
  return MESSAGES[kind]
}

/** Классификация + текст одним шагом — то, что зовёт обработчик очереди. */
export function describeLlmFailure(raw: string | undefined): { kind: LlmFailureKind, message: string } {
  const kind = classifyLlmFailure(raw)
  return { kind, message: llmFailureMessage(kind) }
}

/**
 * Просеянная подпись ошибки ДЛЯ ЖУРНАЛА — коды и латинские токены, ничего больше.
 *
 * ⚠ Почему не пишем строку целиком, хотя это всего лишь журнал: тело ответа провайдера вправе
 * процитировать присланный запрос, а в запросе — текст документа клиента. Журнал такое же
 * хранилище, как база (см. #413), и конвенция проекта прямо запрещает класть туда текст документа.
 * Фильтр по `[A-Za-z0-9_.:-]` выбрасывает кириллицу и пробелы, то есть и наименования товаров, и
 * названия контрагентов — по построению, а не по внимательности пишущего.
 */
export function llmErrorSignature(raw: string | undefined): string {
  return String(raw ?? '')
    // ⚠ Сначала вырезаем эхо ключа, и только потом фильтруем символы — порядок найден живым
    // прогоном (#416): DeepSeek на неверном ключе отвечает «Your api key: ****alid is invalid»,
    // фильтр выбрасывал звёздочки и оставлял в журнале ХВОСТ настоящего ключа. Четырёх знаков мало
    // для подбора, но конвенция проекта запрещает секреты в журнале без оговорок про длину.
    // Метка латиницей — кириллицу следующий фильтр всё равно выбросит, и вышло бы пустое «< >».
    .replace(/(api[\s_-]?key\s*:?\s*)\S+/gi, '$1<hidden>')
    .replace(/[^A-Za-z0-9_.:<>-]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
    .slice(0, 120)
}
