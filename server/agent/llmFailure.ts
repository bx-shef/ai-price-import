// Отказы сервиса распознавания: класс → текст для человека (#416). Чистое ядро, без I/O.
//
// П. 8.4 EULA обещает, что приложение сообщает об отказах в чат Портала. Механически это уже
// работало: `runChatExtract` не бросает, возвращает `{ok:false, error}`, а `failJob` доводит причину
// до сотрудника и в чат ошибок. Проблема была в СОДЕРЖАНИИ причины — до сотрудника доезжала строка
// провайдера как есть:
//
//   • она ничего не объясняет («429 Too Many Requests» не говорит, надо ли повторять и когда);
//   • и её опасно показывать: тело ответа провайдера вправе процитировать присланный запрос, а в
//     запросе лежит текст документа клиента. Пересылать это в чужой рабочий чат нельзя.
//
// Поэтому наружу уходит ТОЛЬКО текст, написанный здесь, а исходная строка не покидает журнал — и
// даже туда идёт просеянной (см. `llmErrorSignature`).

/**
 * Префикс НАШЕЙ собственной строки отказа.
 *
 * ⚠ Существует потому, что классификатор написан для строк ПРОВАЙДЕРА, а через него шли и наши
 * собственные — уже написанные для человека. Живой пример: «слишком много позиций (>10000) —
 * разбейте документ на части» не совпадала ни с одним признаком (в ней нет ни `quota`, ни `429`,
 * ни `context length`) и падала в `unknown`, то есть конкретный исполнимый совет подменялся самым
 * бесполезным текстом из шести — «причина не определена, подробности в журнале», к которому у
 * бухгалтера нет доступа.
 *
 * ⚠ Заплатка «дописать эту фразу в регулярку» не годится: следующая наша строка провалилась бы
 * туда же. Разделять надо источник, а не перечислять формулировки.
 */
export const OWN_FAILURE_PREFIX = 'ours:'

/** Пометить нашу собственную причину отказа — она пойдёт человеку как есть. */
export function ownFailure(message: string): string {
  return `${OWN_FAILURE_PREFIX}${message}`
}

/** Классы отказа, различимые по смыслу для того, кто загрузил документ. */
export type LlmFailureKind
  = | 'quota' // лимит/квота исчерпаны
    | 'auth' // ключ отвергнут или не задан
    | 'unavailable' // провайдер недоступен (5xx, сеть, таймаут)
    | 'too-long' // документ не помещается в контекст модели
    | 'unparsable' // ответ пришёл, но разобрать его не удалось
    | 'own' // наша собственная причина — она уже написана для человека
    | 'unknown' // ни один признак не сработал

// ⚠ Порядок проверок значим, а не косметичен — и он менялся дважды по живым формулировкам.
// Правило простое: первым идёт тот класс, чей СОВЕТ человеку дороже перепутать.
const PATTERNS: Array<[LlmFailureKind, RegExp]> = [
  // ⚠ Ключ ПЕРЕД квотой. Прежде первой стояла квота со словом `billing` в признаках, и живая
  // формулировка «401 Unauthorized: your api key is invalid, contact billing» классифицировалась
  // как исчерпанный лимит: человеку говорили «попробуйте позже», хотя ключ мёртв и ждать
  // бессмысленно — документ не импортировался бы никогда.
  ['auth', /missing api key|not configured|invalid.?api.?key|unauthor|forbidden|\b401\b|\b403\b|authentication/i],
  ['quota', /quota|insufficient_quota|billing|\b429\b|rate.?limit|too many requests|лимит/i],
  ['too-long', /context.?length|maximum context|too many tokens|context_length_exceeded|token limit|too long|prompt is too|слишком длин/i],
  // ⚠ Недоступность ПЕРЕД «не разобрался». Шлюз отдаёт HTML-страницу ошибки, и парсер сообщает
  // «unexpected token < in JSON at position 0» — по голому признаку `json` это читалось как «ответ
  // не разобрался», и совет звучал «проверьте, что таблица в документе читается». То есть мы винили
  // клиента в СВОЕЙ аварии — ровно то, что шапка текстов запрещает.
  ['unavailable', /\b5\d\d\b|overloaded|gateway|unavailable|ECONNRESET|ETIMEDOUT|ENOTFOUND|EAI_AGAIN|socket hang up|timed? ?out|network/i],
  // ⚠ Голого `json` здесь больше нет: он цеплял любую сетевую аварию, отдавшую HTML.
  ['unparsable', /не извлёк|не удалось разобрать|invalid json|unexpected token|malformed json|json.?parse/i]
]

/**
 * Класс отказа по строке ошибки.
 *
 * ⚠ Классификация по тексту сообщения — сознательный компромисс, тот же, что у `classifyAgentError`:
 * у OpenAI-совместимого транспорта разные провайдеры кладут код то в статус, то в тело, и единого
 * машинного признака нет. Неузнанное — `unknown`, а не «сеть»: выдуманный диагноз хуже честного
 * «причина не определена», потому что он уводит человека чинить не то.
 */
export function classifyLlmFailure(raw: string | undefined): LlmFailureKind {
  const m = String(raw ?? '')
  if (!m.trim()) return 'unknown'
  // Наша строка классификации не подлежит: она уже объяснение, а не диагноз по чужому тексту.
  if (m.startsWith(OWN_FAILURE_PREFIX)) return 'own'
  for (const [kind, re] of PATTERNS) if (re.test(m)) return kind
  return 'unknown'
}

// Тексты. Каждый отвечает на три вопроса: что случилось, что делать, будет ли повтор.
//
// ⚠ Ни один НЕ обещает автоматического повтора — его нет: отказ извлечения терминальный, задание
// закрывается, очереди отложенных повторов в проекте намеренно не заведено (решение владельца).
// Обещание «попробуем сами позже» заставило бы человека ждать того, чего не произойдёт.
// ⚠ И ни один не обвиняет клиента в том, что от него не зависит: квота, ключ и доступность —
// наша сторона, и это сказано прямо.
const MESSAGES: Record<LlmFailureKind, string> = {
  // ⚠ Лимит исчерпан НА НАШЕЙ стороне, значит «попробуйте позже» это тупик: сотрудник клиента
  // повлиять на него не может и будет повторять вхолостую. Поэтому названы оба действия — и кому
  // сообщить, и что делать прямо сейчас.
  'quota': 'Исчерпан лимит обращений к сервису распознавания на стороне приложения, документ не обработан. Сообщите издателю: до этого повторять загрузку бесполезно, автоповтора нет.',
  'auth': 'Сервис распознавания отклонил доступ приложения: ключ недействителен. Это неполадка на нашей стороне — сообщите издателю приложения. Документ не обработан.',
  'unavailable': 'Сервис распознавания временно недоступен. Документ не обработан. Загрузите его снова через несколько минут — автоматического повтора нет.',
  'too-long': 'Документ слишком длинный для распознавания. Документ не обработан. Разделите его на части (по разделам или по страницам) и загрузите по отдельности.',
  'unparsable': 'Не удалось разобрать ответ сервиса распознавания: табличная часть не извлечена. Попробуйте загрузить документ ещё раз или проверьте, что таблица в нём читается.',
  // ⚠ Заглушка: до неё не доходит — `describeLlmFailure` отдаёт нашу строку дословно. Нужна, чтобы
  // карта оставалась исчерпывающей по типу (иначе новый класс можно было бы забыть).
  'own': 'Импорт остановлен: документ не обработан.',
  // ⚠ «Подробности в журнале приложения» — тупик: журнал у издателя, у сотрудника клиента доступа
  // к нему нет. Раз своих действий не осталось, текст обязан назвать чужие: номер задания и адрес,
  // по которому его можно передать.
  'unknown': 'Не удалось распознать документ: причина не определена, документ не обработан. Попробуйте ещё раз; если повторится — сообщите издателю приложения, назвав номер задания. Автоповтора нет.'
}

/**
 * Все классы — ВЫВЕДЕНЫ из карты текстов, а не написаны рядом.
 *
 * ⚠ Рукописный список был ровно той второй копией, от которой он же обещал защищать: проверка
 * сверяла только ДЛИНУ, поэтому замена одного класса дублем другого (`auth` → второй `quota`)
 * проходила молча — живая проверка честно печатала шесть галочек, а самый частый отказ (мёртвый
 * ключ) не проверялся вовсе. Здесь расхождение невозможно по построению, и отдельная проверка с
 * `throw` на загрузке модуля не нужна: она роняла бы весь воркер ради инварианта времени разработки.
 */
export const LLM_FAILURE_KINDS = Object.keys(MESSAGES) as LlmFailureKind[]

/**
 * Классы, которые выводятся ИЗ СТРОКИ ПРОВАЙДЕРА, — то, что проверяет живой прогон.
 *
 * ⚠ `own` сюда не входит: у него нет строки провайдера, он приходит от нас самих.
 */
export const PROVIDER_FAILURE_KINDS = LLM_FAILURE_KINDS.filter(k => k !== 'own')

/** Текст отказа для сотрудника. Единственное, что уходит наружу. */
export function llmFailureMessage(kind: LlmFailureKind): string {
  return MESSAGES[kind]
}

/** Классификация + текст одним шагом — то, что зовёт обработчик очереди. */
export function describeLlmFailure(raw: string | undefined): { kind: LlmFailureKind, message: string } {
  const kind = classifyLlmFailure(raw)
  // ⚠ Наша строка уходит человеку ДОСЛОВНО, без подстановки текста класса: она конкретнее любого
  // общего объяснения («разбейте документ на части» против «причина не определена»).
  if (kind === 'own') return { kind, message: String(raw).slice(OWN_FAILURE_PREFIX.length).trim() }
  return { kind, message: llmFailureMessage(kind) }
}

/**
 * Просеянная подпись ошибки ДЛЯ ЖУРНАЛА — только КОДЫ, белым списком.
 *
 * ⚠ Прежний фильтр был ЧЁРНЫМ списком символов (выбрасывал всё, кроме латиницы и цифр), и
 * комментарий уверял, что этого достаточно, «потому что кириллица уходит». Это верно ровно для
 * документов на русском. Проходили насквозь:
 *   • английский инвойс — `ACME Trading Ltd INVOICE 2026-0431 Widget assembly 1200.00 EUR`;
 *   • и, что хуже, ЛЮБЫЕ ЦИФРЫ — а именно они и есть самое чувствительное: УНП/ИНН, номер счёта,
 *     суммы. «поставщик ООО «Ромашка», УНП 191234567, сумма 10320.00» давало в журнале
 *     `191234567 10320.00` — кириллица ушла, идентификатор налогоплательщика и сумма остались.
 * Тесты этого не ловили, потому что проверяли ровно тот случай, который работал (кириллицу).
 *
 * Поэтому теперь БЕЛЫЙ список токенов: оператору нужны коды, а не текст. Оставляем HTTP-статус,
 * `snake_case`-коды провайдеров, коды сети (`ECONNRESET`) и короткие известные слова. Всё
 * остальное — включая любое число длиннее трёх знаков — выбрасывается по построению.
 */
export function llmErrorSignature(raw: string | undefined): string {
  const cleaned = String(raw ?? '')
    // Эхо ключа вырезается ПЕРВЫМ: живой прогон показал «Your api key: ****alid is invalid», и
    // фильтр ниже выбрасывал звёздочки, оставляя хвост настоящего ключа.
    .replace(/(api[\s_-]?key\s*:?\s*)\S+/gi, '$1<hidden>')
  const out: string[] = []
  for (const token of cleaned.split(/[^\w.<>-]+/)) {
    if (!token) continue
    const keep = token === '<hidden>'
      // HTTP-статус: ровно три цифры. Более длинное число — это УНП, сумма или номер, не код.
      || /^\d{3}$/.test(token)
      // Код провайдера (`insufficient_quota`, `context_length_exceeded`) или код сети (`ECONNRESET`).
      || /^[a-z]+(_[a-z]+)+$/.test(token)
      || /^E[A-Z]{3,}$/.test(token)
      // Короткие латинские слова из формулировок статусов — без них подпись нечитаема.
      || KNOWN_WORDS.has(token.toLowerCase())
    if (keep) out.push(token)
  }
  return out.join(' ').slice(0, 120)
}

/**
 * Слова, которые оператору полезны и содержимым документа быть не могут.
 *
 * ⚠ Список закрытый НАМЕРЕННО: «пропускать все короткие латинские слова» вернуло бы английский
 * инвойс по частям.
 */
const KNOWN_WORDS = new Set([
  'unauthorized', 'forbidden', 'quota', 'billing', 'gateway', 'unavailable', 'timeout', 'overloaded',
  'authentication', 'invalid', 'expired', 'exceeded', 'json', 'parse', 'error', 'bad', 'request',
  'internal', 'server', 'service', 'network', 'connection', 'reset', 'refused', 'aborted', 'limit',
  'rate', 'context', 'length', 'tokens', 'maximum', 'model', 'api', 'key', 'fails', 'failed'
])
