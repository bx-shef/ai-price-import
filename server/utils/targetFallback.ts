import { isAuthRejection } from './b24Rest'

// Когда отказ портала при создании записи законно лечится ЗАПАСНОЙ СДЕЛКОЙ, а когда — не лечится
// ничем и задание обязано упасть (#492, решение владельца 10.08.2026).
//
// ⚠ ФОРМУЛИРОВКА ВЛАДЕЛЬЦА, из которой всё следует: «если у Б24 что-то не так — то мы и сделку не
// создадим». То есть падение здесь не деградация, а нужное поведение: упавшее задание видно в
// списке неудачных на `/queues`, попадает в тревогу по очередям и чинится повтором — сам собой,
// когда портал отпустит, или после того, как владелец вернёт права.
//
// ⚠ Чем платили до этой функции. `crmSyncCore` ловил создание голым `catch` и уводил документ в
// сделку направления 0 при ЛЮБОЙ причине. Два следствия, и второе хуже первого:
//
//   1. На настоящей поломке портала (`ACCESS_DENIED`, отозванный токен, предел частоты, таймаут)
//      второй вызов `createTarget` упирается в ТО ЖЕ САМОЕ. Мы делали лишний REST-вызов к сломанному
//      порталу, получали то же исключение шагом позже и вдобавок затирали причину: наружу уходило
//      «возможно, этот тип отключён в вашей CRM», хотя тип ни при чём.
//   2. А если запасной вызов всё-таки проходил — права на смарт-процесс отозвали, а на сделки
//      остались; предел частоты пришёлся на первый вызов и отпустил ко второму, — документ
//      НЕОБРАТИМО уезжал в чужую воронку, задание помечалось успешным, и ни в список неудачных, ни в
//      тревогу это не попадало. Повтором такое не лечится: карточка уже создана.
//
// ⚠ Поэтому список **разрешающий и закрытый**, а не запрещающий: неузнанный отказ читается как «у
// портала что-то не так» и роняет задание. Цена ошибки несимметрична — ложное падение стоит
// повтора, ложный успех стоит карточки в чужой воронке, которую никто не заметит.

/** Явное «такого типа здесь нет» от портала. Единственная формулировка, которую он даёт на
 *  отключённый смарт-счёт и на удалённый смарт-процесс — та же, что ловит `probeSmartInvoiceEnabled`
 *  (`typeLookup.ts`), и проверена вживую на `T1120` против `T460`. */
const TARGET_MISSING = /не\s+поддерживается|not\s+supported|ENTITY_TYPE_NOT_SUPPORTED|CRM_ENTITY_TYPE_NOT_FOUND/i

/**
 * Означает ли отказ портала, что запись просто **некуда** класть — тип отключён, направление
 * удалили, — и потому уместна запасная сделка.
 *
 * ⚠ Отказ авторизации проверяется ПЕРВЫМ и всегда даёт `false`. Причина не в порядке ради порядка:
 * ответ портала на отозванные права может нести обе приметы разом (`403 … entity type not
 * supported` встречается), а советы противоположные — при мёртвых правах создавать нечего вообще.
 *
 * ⚠ Голый `NOT_FOUND` НЕ считается «типа нет»: Битрикс24 отдаёт его по десятку причин, и трактовать
 * его как отсутствие цели значит вернуть ровно тот дефект, ради которого функция написана. Тот же
 * вывод уже сделан в `typeLookup.probeSmartInvoiceEnabled` и закреплён там комментарием.
 */
export function isMissingTargetError(err: unknown): boolean {
  if (isAuthRejection(err)) return false
  const msg = err instanceof Error ? err.message : String(err)
  return TARGET_MISSING.test(msg)
}
