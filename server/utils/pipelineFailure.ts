/**
 * Отказ на НАШЕЙ стороне конвейера: что показать человеку и к кому его отправить (#506).
 *
 * ЖИВАЯ НАХОДКА (прогон владельца 10.08.2026, намеренно битый `.txt`). На экране было:
 *
 *   «Не удалось обработать документ… покажите это сообщение АДМИНИСТРАТОРУ.
 *    Подробности: invalid byte sequence for encoding "UTF8": 0x00»
 *
 * Здесь неверно и то, и другое.
 *
 * **Адресат.** Это ветка НЕ-CRM стадий: файл не разобрался у нас, до портала дело не дошло.
 * Администратор портала не может сделать ничего — у него нет ни файла, ни журналов, ни доступа к
 * конвейеру. Отправляя к нему, мы отправляем человека к тому, кто заведомо не поможет, и теряем
 * сигнал: до разработчика он не доходит.
 *
 * ⚠ Правило, которого раньше не было и которое теперь записано: **наш отказ → к разработчику,
 * отказ портала → к администратору.** Второе место (`app/utils/importFailure.ts`) адресует
 * администратору, и там это ВЕРНО: портал отказал в правах или тип записи выключен — чинит именно
 * он. Разница не в вежливости, а в том, ЧЬЯ это поломка.
 *
 * **Подробности.** `invalid byte sequence…` — ответ Postgres. Сотруднику он не говорит ничего, а
 * наружу выносит внутреннее устройство. Тот же запрет, по которому мы не показываем строку
 * поставщика модели (#416): наружу уходит ТОЛЬКО наш текст.
 *
 * ⚠ Полностью прятать причину тоже нельзя: «неподдерживаемый формат файла: смета.zip» — это наш
 * собственный текст, он написан для человека и отвечает на вопрос «что делать». Поэтому решение
 * двоичное и по БЕЛОМУ списку: узнали свой отказ — показали его; всё остальное — общий текст без
 * внутренностей.
 */

/** Что за отказ. */
export type PipelineFailureKind
  /** Наш собственный текст, написанный для человека (формат, размер, пустой документ). */
  = | 'own'
  /** Файл не прочитался: битый, недокачанный, не тот формат внутри. */
    | 'unreadable'
  /** Всё прочее — внутренняя поломка, о которой человеку сказать нечего. */
    | 'internal'

/**
 * Наши собственные отказы, которые МОЖНО показать целиком.
 *
 * ⚠ Список ЗАКРЫТЫЙ и по началу строки, а не по форме: «покажем, если похоже на человеческий
 * текст» пропустило бы наружу любое сообщение библиотеки на русском. Заводя новый отказ в
 * конвейере, добавляй его сюда явно — иначе он приедет к человеку общим текстом, и это правильный
 * исход по умолчанию.
 */
const OWN_PREFIXES = [
  'неподдерживаемый формат файла',
  'файл пустой',
  'файл слишком большой',
  'в документе не нашлось таблицы'
]

/**
 * Признаки того, что файл просто не читается.
 *
 * ⚠ Нулевой байт сюда входит НАМЕРЕННО, хотя это и ответ базы: для человека это ровно «файл битый»,
 * и общий текст «внутренняя ошибка» увёл бы его к разработчику там, где он чинит сам за минуту.
 * Сам текст базы при этом наружу всё равно не идёт — мы берём из него только классификацию.
 */
const UNREADABLE_PATTERNS = [
  /invalid byte sequence/i,
  /0x00/,
  /malformed|corrupt|damaged/i,
  /не удалось (?:раз|про)?(?:обрать|читать)/i
]

export function classifyPipelineFailure(raw: string | undefined | null): PipelineFailureKind {
  const m = String(raw ?? '').trim().toLowerCase()
  if (!m) return 'internal'
  if (OWN_PREFIXES.some(p => m.startsWith(p))) return 'own'
  if (UNREADABLE_PATTERNS.some(re => re.test(m))) return 'unreadable'
  return 'internal'
}

/**
 * Куда вести человека дальше.
 *
 * ⚠ Формулировка ведёт ПО ШАГАМ, а не сваливает всё сразу (решение владельца): сперва «откройте
 * файл сами», и только если он открывается — «пришлите разработчику». Половина таких случаев —
 * недокачанный или повреждённый при выгрузке из 1С файл, и человек чинит это за минуту без
 * переписки. Свалив оба шага в одну фразу, мы гарантированно получаем письмо там, где хватило бы
 * повторной выгрузки.
 */
const CHECK_FIRST = 'Сначала откройте этот файл у себя на компьютере — открывается ли он? Если нет, '
  + 'выгрузите его заново и загрузите ещё раз.'
const THEN_DEVELOPER = 'Если файл открывается, а импорт всё равно не проходит — отправьте его '
  + 'разработчику кнопкой ниже: без самого файла воспроизвести не получится.'

/**
 * Текст для человека.
 *
 * ⚠ Ни в одном исходе НЕТ слова «администратор»: это ветка нашей стороны конвейера, и администратор
 * портала здесь бессилен. Гард на это стоит в тестах.
 */
export function describePipelineFailure(raw: string | undefined | null): { kind: PipelineFailureKind, message: string } {
  const kind = classifyPipelineFailure(raw)
  if (kind === 'own') {
    // Свой текст уже написан для человека — печатаем как есть и добавляем шаги.
    const own = String(raw ?? '').trim()
    return { kind, message: `Импорт остановлен: ${own}. ${CHECK_FIRST}` }
  }
  if (kind === 'unreadable') {
    return {
      kind,
      message: `Импорт остановлен: файл не удалось прочитать — похоже, он повреждён или скачался не полностью. ${CHECK_FIRST} ${THEN_DEVELOPER}`
    }
  }
  return {
    kind,
    message: `Импорт остановлен: документ обработать не удалось. ${CHECK_FIRST} ${THEN_DEVELOPER}`
  }
}
