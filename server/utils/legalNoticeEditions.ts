import { PENDING_LEGAL_EDITIONS } from '../../app/config/legalNotice'
import { editionKey } from '../../app/utils/legalNotice'

// Серверный взгляд на объявленные редакции (#418).
//
// ⚠ Существует ради одной вещи: ключ редакции, приходящий из браузера, обязан сверяться со СПИСКОМ
// СЕРВЕРА. Иначе страница могла бы записать порталу отметку о доставке уведомления, которого не
// было, — подделать доказательство против самого лицензиата. Список объявлений — данные приложения,
// клиенту тут нечего добавить.

/** Ключи всех объявленных (в конфиге) редакций — включая уже вступившие в силу. */
export function announcedEditionKeys(): string[] {
  return PENDING_LEGAL_EDITIONS.map(editionKey)
}
