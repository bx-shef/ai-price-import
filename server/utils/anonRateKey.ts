import { createHmac, randomBytes, timingSafeEqual } from 'node:crypto'

// Ключ ограничения частоты БЕЗ хранения IP-адреса (#413).
//
// Зачем. В облачном сценарии оператор персональных данных — клиент, установивший приложение, а
// издатель обработчик по его поручению. В ДЕМО-разборе это не работает: посетитель сайта ничего не
// устанавливал и поручения не давал, цели и состав обработки определяет издатель. Значит всё, что
// демо сохраняет о посетителе, делает издателя владельцем персональных данных по Закону № 99-З и
// оператором по 152-ФЗ — с уведомлением Роскомнадзора и вопросом локализации.
//
// Единственное, что реально образовывало персональные данные в демо, — IP-адрес в ключе счётчика
// частоты. Он лежал в памяти процесса открытым текстом (`Map<ip, timestamps[]>`). Здесь он
// заменяется необратимым отпечатком, и предмет исчезает: хранить нечего, выдавать нечего,
// удалять нечего.
//
// ⚠ Почему именно HMAC с секретом, а не голый SHA-256. Пространство IPv4 — 4·10⁹ адресов, это
// перебирается на ноутбуке за минуты: голый хеш от IP обратим по построению и персональными
// данными быть не перестаёт. Секрет делает перебор бессмысленным — не зная его, отпечаток нельзя
// сопоставить ни с одним адресом.
//
// ⚠ Секрет живёт ТОЛЬКО в памяти процесса и нигде не персистится: ни в env, ни в базе, ни в
// журнале. Перезапуск процесса рождает новый секрет — счётчики при этом обнуляются, и это
// осознанная плата. Ограничение частоты защищает от цикла и от расхода LLM-бюджета, а не от
// злоумышленника, который ради трёх лишних разборов ждёт нашего рестарта; бюджет суток (#321)
// перезапуском не сбрасывается и держит расход независимо.

/** Длина отпечатка в hex-символах. 32 (=128 бит) — коллизий не будет, а ключ втрое короче полного. */
const FINGERPRINT_HEX = 32

/**
 * Секрет процесса. Генерируется лениво при первом обращении, чтобы импорт модуля был бесплатным
 * и не тратил энтропию в тестах/сборке, которые его не используют.
 */
let processSecret: Buffer | null = null

function secret(): Buffer {
  if (!processSecret) processSecret = randomBytes(32)
  return processSecret
}

/**
 * Отпечаток обращения: `HMAC-SHA256(ipBucket + '|' + userAgent, секрет процесса)`.
 *
 * User-agent подмешан не ради точности, а ради энтропии: за одним домашним адресом сидит несколько
 * устройств, и без него они делят одно ведро. Это не идентификация устройства — строка не хранится
 * и в отпечатке неотличима от адреса.
 *
 * @param ipKey ключ, который построил `rateLimitKey` (уже свёрнутый до /64 у IPv6).
 * @param userAgent заголовок `User-Agent` запроса, если он есть.
 */
export function anonRateKey(ipKey: string, userAgent: string | undefined): string {
  return createHmac('sha256', secret())
    .update(`${ipKey}|${(userAgent ?? '').slice(0, 256)}`)
    .digest('hex')
    .slice(0, FINGERPRINT_HEX)
}

/**
 * Тестовый вариант с явным секретом — детерминированный, поэтому поведение отпечатка проверяется
 * без обращения к секрету процесса. Прод-путь идёт через `anonRateKey`.
 */
export function anonRateKeyWith(ipKey: string, userAgent: string | undefined, key: Buffer | string): string {
  return createHmac('sha256', key)
    .update(`${ipKey}|${(userAgent ?? '').slice(0, 256)}`)
    .digest('hex')
    .slice(0, FINGERPRINT_HEX)
}

/**
 * Проверка «этот отпечаток получен из этого адреса» — только для тестов и разбора инцидентов на
 * своём стенде. Сравнение постоянного времени: функция принимает пару со стороны вызывающего, и
 * побайтовое сравнение здесь дало бы оракул на подбор.
 *
 * ⚠ В проде вызывать неоткуда и незачем: у нас нет ни адреса, с которым можно сверять, ни задачи,
 * которая этого требует. Функция существует, чтобы утверждение «отпечаток соответствует адресу»
 * можно было проверить тестом, а не принять на слово.
 */
export function matchesAnonKey(fingerprint: string, ipKey: string, userAgent: string | undefined, key: Buffer | string): boolean {
  const expected = anonRateKeyWith(ipKey, userAgent, key)
  if (fingerprint.length !== expected.length) return false
  return timingSafeEqual(Buffer.from(fingerprint), Buffer.from(expected))
}
