// Кэш базовой валюты портала на короткий срок (#480).
//
// ЗАЧЕМ. Чтение настроек стоит трёх обращений к Битрикс24, и одно из них — базовая валюта. Она нужна
// ровно для подписи к ставке часа и меняется на портале примерно никогда, а спрашивалась при КАЖДОМ
// перечитывании настроек. Рассылка настроек будит все открытые экраны портала разом, и этот вызов
// умножался на число вкладок вместе с остальными — то есть самый бесполезный из трёх стоил столько
// же, сколько нужные.
//
// ⚠ Кэш ПАМЯТИ ПРОЦЕССА, не Redis, и это решение. Реплик может быть несколько, и каждая заведёт свой
// — значит всплеск режется не в N раз, а в N/реплик. Этого достаточно: цель не «один запрос на
// портал», а «не полторы сотни за секунду». Общий кэш в Redis стоил бы обращения к Redis вместо
// обращения к порталу — то есть дешевле, но не бесплатно, и добавил бы новую точку отказа на пути,
// который обязан переживать отсутствие Redis.
//
// ⚠ Отказ чтения НЕ КЭШИРУЕТСЯ. «Валюты нет» и «не смогли прочитать» — разные исходы: первый экран
// заявляет как факт и отправляет админа заводить валюту. Закэшировав отказ, мы бы держали это
// ложное утверждение все десять минут, причём у всех сотрудников сразу.

/** Сколько живёт запомненное значение. Минуты, а не часы: всплеск длится секунды, а неверно
 *  запомненная валюта живёт до истечения. */
export const BASE_CURRENCY_TTL_MS = 10 * 60 * 1000

interface Entry {
  code: string | null
  expiresAt: number
}

const cache = new Map<string, Entry>()

/**
 * Прочитать базовую валюту портала, переиспользуя недавний ответ.
 *
 * ⚠ Ключ — ДОМЕН ПОРТАЛА, и он приходит из проверенного фрейм-токена. Взять его из тела запроса
 * значило бы позволить одному порталу прочитать закэшированное значение другого; сама валюта не
 * секрет, но кэш, ключуемый клиентским значением, — это способ смешать данные тенантов, и заводить
 * такую привычку нельзя.
 */
export async function cachedBaseCurrency(
  portal: string,
  read: () => Promise<string | null>,
  now: () => number = Date.now
): Promise<{ code: string | null, failed: boolean, cached: boolean }> {
  const key = String(portal || '').toLowerCase()
  const hit = key ? cache.get(key) : undefined
  if (hit && hit.expiresAt > now()) return { code: hit.code, failed: false, cached: true }
  try {
    const code = await read()
    if (key) cache.set(key, { code, expiresAt: now() + BASE_CURRENCY_TTL_MS })
    return { code, failed: false, cached: false }
  } catch {
    return { code: null, failed: true, cached: false }
  }
}

/** Забыть запомненное — нужно при удалении портала и в тестах. */
export function forgetBaseCurrency(portal?: string): void {
  if (portal === undefined) {
    cache.clear()
    return
  }
  cache.delete(String(portal || '').toLowerCase())
}
