// Кэш базовой валюты портала на короткий срок (#480).
//
// ЗАЧЕМ. Чтение настроек стоит трёх обращений к Битрикс24, и одно из них — базовая валюта. Она нужна
// ровно для подписи к ставке часа и меняется на портале примерно никогда, а спрашивалась при КАЖДОМ
// перечитывании настроек. Рассылка настроек будит все открытые экраны портала разом, и этот вызов
// умножался на число вкладок вместе с остальными — то есть самый бесполезный из трёх стоил столько
// же, сколько нужные.
//
// ⚠ Кэш ПАМЯТИ ПРОЦЕССА, не Redis, и это решение. Реплик может быть несколько, и каждая заведёт свой
// — значит всплеск режется не в N раз, а в N/реплик. Этого достаточно: цель не «один запрос на
// портал», а «не полторы сотни за секунду». Общий кэш в Redis стоил бы обращения к Redis вместо
// обращения к порталу — то есть дешевле, но не бесплатно, и добавил бы новую точку отказа на пути,
// который обязан переживать отсутствие Redis.
//
// ⚠ ПРИ УДАЛЕНИИ ПРИЛОЖЕНИЯ кэш НЕ чистится, и это решение, а не пропуск. Событие удаления
// обрабатывает ОДИН процесс, а кэш живёт в памяти КАЖДОГО: очистка сняла бы запись у одной реплики
// из N и оставила у остальных — то есть создала бы видимость уборки там, где её нет. Настоящей
// уборкой здесь работает срок: через десять минут запись перестаёт использоваться на всех репликах
// разом. Хранится при этом трёхбуквенный код валюты, не данные клиента.
//
// ⚠ Отказ чтения НЕ КЭШИРУЕТСЯ. «Валюты нет» и «не смогли прочитать» — разные исходы: первый экран
// заявляет как факт и отправляет админа заводить валюту. Закэшировав отказ, мы бы держали это
// ложное утверждение все десять минут, причём у всех сотрудников сразу.

/** Сколько живёт запомненное значение. Минуты, а не часы: всплеск длится секунды, а неверно
 *  запомненная валюта живёт до истечения. */
export const BASE_CURRENCY_TTL_MS = 10 * 60 * 1000

/**
 * Потолок числа порталов в памяти.
 *
 * ⚠ Обязателен, потому что приложение МУЛЬТИТЕНАНТНОЕ: без него карта растёт по числу порталов,
 * когда-либо открывавших настройки, и живёт всё время работы процесса. Истечение срока само по себе
 * память НЕ освобождает — просроченная запись просто перестаёт использоваться и лежит дальше.
 * Тысяча клиентов это несколько десятков килобайт, то есть не авария, но утечка, которая ничем не
 * проявляется и растёт молча; ставить её на путь, открывающий рабочий экран каждого клиента, нельзя.
 */
export const BASE_CURRENCY_MAX_PORTALS = 500

interface Entry {
  code: string | null
  expiresAt: number
}

const cache = new Map<string, Entry>()

/**
 * Освободить место: сперва просроченные, и только если не хватило — самая старая запись.
 *
 * ⚠ Вытеснение «самой старой» здесь законно именно потому, что кэш — ускорение, а не источник
 * правды: выброшенная запись стоит одного лишнего обращения к порталу, а не неверного ответа.
 * `Map` в JS хранит порядок вставки, поэтому первый ключ и есть самый давно записанный.
 */
function makeRoom(now: number): void {
  if (cache.size < BASE_CURRENCY_MAX_PORTALS) return
  for (const [key, entry] of cache) {
    if (entry.expiresAt <= now) cache.delete(key)
  }
  while (cache.size >= BASE_CURRENCY_MAX_PORTALS) {
    const oldest = cache.keys().next().value
    if (oldest === undefined) break
    cache.delete(oldest)
  }
}

/**
 * Прочитать базовую валюту портала, переиспользуя недавний ответ.
 *
 * ⚠ Ключ — ДОМЕН ПОРТАЛА, и он приходит из проверенного фрейм-токена. Взять его из тела запроса
 * значило бы позволить одному порталу прочитать закэшированное значение другого; сама валюта не
 * секрет, но кэш, ключуемый клиентским значением, — это способ смешать данные тенантов, и заводить
 * такую привычку нельзя.
 */
export async function cachedBaseCurrency(
  portal: string,
  read: () => Promise<string | null>,
  now: () => number = Date.now
): Promise<{ code: string | null, failed: boolean, cached: boolean }> {
  const key = String(portal || '').toLowerCase()
  const hit = key ? cache.get(key) : undefined
  if (hit && hit.expiresAt > now()) return { code: hit.code, failed: false, cached: true }
  try {
    const code = await read()
    if (key) {
      makeRoom(now())
      cache.set(key, { code, expiresAt: now() + BASE_CURRENCY_TTL_MS })
    }
    return { code, failed: false, cached: false }
  } catch {
    return { code: null, failed: true, cached: false }
  }
}

/**
 * Забыть запомненное.
 *
 * ⚠ Зовётся ТОЛЬКО из тестов, и это следствие решения выше, а не забытый крюк. Прежняя редакция
 * подписи обещала «нужно при удалении портала» — и обещание было бы неправдой в коде: чистить кэш на
 * удалении бессмысленно, событие обрабатывает один процесс, а кэш живёт в памяти каждого. Подпись,
 * опережающая код, читается следующим как незакрытый крюк, и он его «дочинит» полумерой.
 */
export function forgetBaseCurrency(portal?: string): void {
  if (portal === undefined) {
    cache.clear()
    return
  }
  cache.delete(String(portal || '').toLowerCase())
}
