import { siteBaseUrl } from '../../app/utils/landing'

// Абсолютные адреса юридических документов для сообщения в чат (#418).
//
// ⚠ Живёт ОТДЕЛЬНЫМ модулем, а не в `liveDeps.ts`, и это не вкусовщина: там стоит гард (#385),
// запрещающий упоминание нашего хоста во всей проводке — прежняя ссылка «открыть приложение»
// собиралась от него и вела в тупик, потому что вне портала нет ни фрейма, ни фрейм-токена.
// Гард абсолютен намеренно: регрессия жила на месте вызова, а не в теле функции. Здесь случай
// прямо противоположный — юридические документы физически живут на НАШЕМ сайте, портальной ссылки
// у них нет и быть не может, — поэтому исключение вынесено в отдельный файл, а не пробито в гарде.

/** Абсолютный адрес страницы документа: чат не понимает относительных ссылок. */
export function legalDocUrl(path: string): string {
  return `${siteBaseUrl(process.env.NUXT_PUBLIC_SITE_URL)}${path}`
}
