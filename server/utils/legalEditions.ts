import type { LegalEdition } from '../../app/utils/legalEdition'

// Действующие редакции документов ПРИЛОЖЕНИЯ, как их видит сервер (#414).
//
// ⚠ Редакции берутся ЗДЕСЬ, а не из тела запроса. Запись о согласии — доказательство, и
// доказательство, содержание которого диктует проверяемая сторона, ничего не стоит: клиент,
// приславший `{eula:'01.01.2020'}`, задним числом «согласился» с редакцией, которой не видел.
// Сервер знает, какие тексты он сам отдаёт на `/eula` и `/privacy`, и фиксирует именно их.
//
// Значения приезжают из `runtimeConfig.legalEditions`, куда `nuxt.config.ts` кладёт их на сборке,
// прочитав сами документы. Прямой `?raw`-импорт здесь невозможен: rollup Nitro этот суффикс не
// разбирает и падает на сборке (в отличие от клиентского Vite, которым живут страницы `/eula`
// и `/privacy`).
//
// ⚠ Пара документов именно ПРИЛОЖЕНИЯ. Документы сайта (`site-terms`/`site-privacy`) сюда не
// входят: их принимает посетитель демо, который приложение не устанавливал (#297). Сегодня даты у
// всех четырёх совпадают — и это совпадение, а не правило.

export interface CurrentEditions { eula: LegalEdition, privacy: LegalEdition }

export function currentEditions(): CurrentEditions {
  return useRuntimeConfig().legalEditions as CurrentEditions
}
