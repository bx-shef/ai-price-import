/**
 * Очистка извлечённого текста документа (#506).
 *
 * ЗАЧЕМ. Живой прогон с битым `.txt` кончился ответом Postgres «invalid byte sequence for encoding
 * "UTF8": 0x00». То есть нулевой байт из файла клиента доезжал по конвейеру до самой записи в базу —
 * и падало там, где о документе уже никто не думает. Текст сообщения был лишь симптомом: настоящий
 * дефект в том, что мусор из файла вообще пошёл дальше извлечения.
 *
 * ⚠ Чистим В ОДНОЙ ТОЧКЕ — сразу после извлечения. Ставить защиту у каждого приёмника (база,
 * очередь, спаны, отзыв) значит завести четыре копии правила, которые разойдутся; а пропустивший
 * приёмник найдётся ровно тогда, когда о нём забудут.
 */

/**
 * Управляющие символы C0/C1, кроме переводов строки и табуляции.
 *
 * ⚠ Записаны escape-последовательностями намеренно: литеральные управляющие символы в исходнике
 * невидимы, и правка такого класса «на глаз» неизбежно ломает диапазон.
 */
// eslint-disable-next-line no-control-regex -- ровно эти символы и вычищаем
const CONTROL_CHARS = /[\u0000-\u0008\u000B\u000C\u000E-\u001F\u007F-\u009F]/g

/**
 * Сколько «читаемого» должно остаться, чтобы считать документ текстом.
 *
 * ⚠ Порог мягкий и намеренно: документ бывает почти пустым законно (скан, где OCR нашёл три
 * строки), и отказать такому значило бы сломать рабочий сценарий ради красивой проверки. Отсекаем
 * только заведомый мусор — когда после чистки не осталось практически ничего.
 */
export const MIN_READABLE_CHARS = 16

export interface SanitizedText {
  text: string
  /** Сколько символов вычистили. Ноль — файл был чистым. */
  removed: number
  /** Осталось ли достаточно, чтобы вообще пытаться разбирать. */
  readable: boolean
}

/**
 * Убрать из текста то, что не может нести смысла и ломает хранение.
 *
 * ⚠ Переводы строки и табуляция СОХРАНЯЮТСЯ: в них держится табличная структура документа, ради
 * которой всё и затевается. Вычистив их «заодно», мы превратили бы накладную в кашу и сломали бы
 * извлечение позиций — дефект, который выглядел бы как «нейросеть стала хуже разбирать».
 */
export function sanitizeExtractedText(raw: string | null | undefined): SanitizedText {
  const src = String(raw ?? '')
  const text = src.replace(CONTROL_CHARS, '')
  const removed = src.length - text.length
  return { text, removed, readable: text.replace(/\s/g, '').length >= MIN_READABLE_CHARS }
}
