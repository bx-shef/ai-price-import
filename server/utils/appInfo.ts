import type { RestCall } from './b24Rest'

/**
 * Локальный идентификатор НАШЕГО приложения на портале (`app.info` → `ID`).
 *
 * ⚠ Зачем вообще: адрес, которым мы возвращаем человека в приложение, — `/marketplace/app/<ID>/`,
 * и `ID` свой на каждом портале. Символьный код карточки Маркета для этого не годится: живой прогон
 * 09.08.2026 показал, что `/marketplace/view/<код>/` на портале не открывается (см. `portalAppUrl`).
 *
 * ⚠ Метод отвечает ТОЛЬКО в контексте приложения — вебхуком его не позвать (`ACCESS_DENIED:
 * Application context required`). Поэтому вызывать его можно лишь на OAuth-пути (воркер), и живые
 * скрипты, ходящие вебхуком, ссылку не получат — это ожидаемо, а не поломка.
 *
 * ⚠ Отказ — `null`, а не исключение: ссылка это удобство, а уведомление — суть. Сообщение о неудаче
 * обязано доехать даже если портал не ответил про приложение.
 */
export async function fetchAppId(call: RestCall): Promise<number | null> {
  try {
    const res = await call('app.info', {}) as { ID?: unknown } | null
    // Портал отдаёт `ID` то числом, то строкой — приводим сами и проверяем как целое положительное.
    const id = Number((res as { ID?: unknown } | null)?.ID)
    return Number.isInteger(id) && id > 0 ? id : null
  } catch {
    return null
  }
}
