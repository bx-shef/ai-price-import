import type { PortalConsent } from './consentStore'

// Решение «принимать ли документ от этого портала» (#414). Чистая функция — поведение гейта
// проверяется тестом, а не только его наличие в роуте.
//
// Зачем гейт на сервере, если экран согласия и так закрывает интерфейс. Экран — это удобство и
// место, где человек читает текст; границей он быть не может. `/api/import/upload` вызывается по
// фрейм-токену, то есть чем угодно, что этот токен раздобыло, — сам портал в этом смысле не
// авторитет. Юридическая конструкция держится на том, что НИ ОДИН документ не ушёл на инференс до
// подтверждения прав, и держать это обязан тот слой, который документы принимает.

export interface ConsentDecision {
  allowed: boolean
  /** HTTP-код отказа. */
  status: number
  /** Текст для сотрудника — попадает в интерфейс импорта как есть. */
  message: string
}

export const CONSENT_REQUIRED_MESSAGE
  = 'Администратор портала ещё не принял Лицензионное соглашение и Политику конфиденциальности. '
    + 'Откройте приложение под администратором и подтвердите условия — после этого импорт заработает.'

/**
 * ⚠ Отказ — **403, а не 409**: условия не приняты — это состояние прав, а не конфликт состояния, и
 * клиент отличает его от «портал не установлен» (401) и от «очередь недоступна» (503).
 *
 * ⚠ `null` (строки нет) и «не смогли прочитать» здесь НЕ различаются и не должны: fail-open
 * означал бы, что первый же сбой базы пропускает документы мимо подтверждения — то самое, чего вся
 * конструкция не допускает. Читающая сторона обязана падать наружу, а не подставлять `null`.
 */
export function consentGate(consent: PortalConsent | null): ConsentDecision {
  if (consent) return { allowed: true, status: 200, message: '' }
  return { allowed: false, status: 403, message: CONSENT_REQUIRED_MESSAGE }
}
