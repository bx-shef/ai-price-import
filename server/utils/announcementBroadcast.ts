import { buildAnnouncementEvent } from '~/utils/announcementPull'
import type { RestCall } from './b24Rest'

// Рассылка сигнала «проверь объявление» по ВСЕМ установившим порталам (#478).
//
// ⚠ Отличие от синхронизации настроек, из-за которого нельзя было просто скопировать её код:
// событие настроек портал шлёт САМ СЕБЕ — вызов идёт из фрейма админа, в контексте его портала.
// Объявление публикует ИЗДАТЕЛЬ, у которого фрейма нет вовсе: публикация идёт из консоли оператора,
// серверным запросом. Значит отправитель — сервер, а получателей столько, сколько порталов, и
// каждому нужен свой токен.
//
// ⚠ РАССЫЛКА НЕ ВПРАВЕ ЗАВАЛИТЬ ПУБЛИКАЦИЮ. Объявление уже записано в хранилище и доедет до людей
// при открытии экрана — это работало до #478 и остаётся запасным путём. Рассылка лишь ускоряет
// доставку, поэтому её отказ — это строка в отчёте, а не ошибка операции.
//
// ⚠ НО МОЛЧАТЬ О НЕЙ НЕЛЬЗЯ: молчаливо провалившаяся рассылка неотличима от «никто не открывал
// экран», и владелец ждал бы реакции на объявление, которого никто не получил. Отсюда сводка с
// разбивкой по классам отказа — она уходит оператору в ответ роута.

/** Класс отказа доставки на ОДИН портал. Только класс — текст ошибки портала наружу не идёт. */
export type BroadcastFailure
  /** Нет живого токена: портал удалил приложение, а событие деинсталляции ещё не доехало. */
  = | 'no-token'
    /** Портал отверг вызов: нет скоупа `pull`, выключен pull-сервер, истёк грант. */
    | 'refused'

export interface BroadcastSummary {
  /** Сколько порталов было в выборке (после капа). */
  total: number
  /** Скольким доставлено. */
  sent: number
  /** Скольким не удалось. */
  failed: number
  /** Разбивка отказов по классам — по ней видно, это наша поломка или разъехавшиеся клиенты. */
  byReason: Partial<Record<BroadcastFailure, number>>
  /**
   * Выборка упёрлась в кап — часть порталов НЕ получила сигнал.
   *
   * ⚠ Отдельное поле, а не молчание: «разослали всем» и «разослали первым пятистам» выглядят в
   * отчёте одинаково, если про кап не сказать. Тот же приём, что у обрезки в сводке отзывов.
   */
  truncated: boolean
}

/**
 * Сколько порталов обходим за одну публикацию.
 *
 * ⚠ Кап есть, хотя порталов сегодня единицы: рассылка идёт по одному REST-вызову на портал, и без
 * границы одна публикация однажды превратилась бы в тысячи обращений подряд. Значение с запасом
 * выше любого правдоподобного числа установок на ближайший год — упереться в него значит, что о
 * рассылке пора думать иначе, и `truncated` об этом скажет.
 */
export const MAX_BROADCAST_PORTALS = 1000

export interface BroadcastDeps {
  /** Идентификаторы порталов (member_id). */
  listPortals: () => Promise<string[]>
  /** Транспорт портала; `null` — живого токена нет. */
  callFor: (memberId: string) => Promise<RestCall | null>
  /** Код приложения = ключ канала. Совпадает с тем, что слушает подписчик. */
  moduleId: string
  log?: (msg: string) => void
}

/**
 * Broadcast the «re-check the announcement» signal to every installed portal.
 *
 * ⚠ Порталы обходятся ПОСЛЕДОВАТЕЛЬНО. Параллельный обход был бы быстрее, но публикация объявления —
 * действие раз в месяц, а всплеск исходящих вызовов ко всем порталам разом ничем не оправдан:
 * выигрыш в секундах против риска упереться в чужие пределы.
 * ⚠ Отказ одного портала НЕ прерывает обход: один криво настроенный клиент не должен лишать сигнала
 * всех остальных — тот же принцип, что у keep-alive рефреша токенов.
 */
export async function broadcastAnnouncement(deps: BroadcastDeps): Promise<BroadcastSummary> {
  const all = await deps.listPortals()
  const portals = all.slice(0, MAX_BROADCAST_PORTALS)
  const summary: BroadcastSummary = {
    total: portals.length,
    sent: 0,
    failed: 0,
    byReason: {},
    truncated: all.length > portals.length
  }
  const params = buildAnnouncementEvent(deps.moduleId)
  for (const memberId of portals) {
    let reason: BroadcastFailure | null = null
    try {
      const call = await deps.callFor(memberId)
      if (!call) reason = 'no-token'
      // ⚠ Приведение к записи, а не `as never`: транспорт принимает свободный набор параметров, а
      // `PullEventParams` — закрытый тип с тремя полями. Форму строит чистая функция, здесь только
      // передача.
      else await call('pull.application.event.add', { ...params })
    } catch {
      // ⚠ В журнал не идёт ни текст ошибки портала, ни member_id: первый вправе процитировать
      // параметры вызова, второй — идентификатор клиента. Класса достаточно, чтобы понять причину.
      reason = 'refused'
    }
    if (reason) {
      summary.failed++
      summary.byReason[reason] = (summary.byReason[reason] ?? 0) + 1
    } else {
      summary.sent++
    }
  }
  deps.log?.(`[announcement] рассылка: доставлено ${summary.sent} из ${summary.total}`
    + (summary.failed ? `, не удалось ${summary.failed} (${JSON.stringify(summary.byReason)})` : '')
    + (summary.truncated ? `, ВЫБОРКА ОБРЕЗАНА до ${MAX_BROADCAST_PORTALS}` : ''))
  return summary
}
