// @vitest-environment nuxt
import { readFileSync } from 'node:fs'
import { describe, expect, it } from 'vitest'

// #443, проводка живой синхронизации настроек и блокировок на время пачки.
//
// Чистое правило (`settingsAdopt`) покрыто отдельно, и этого не хватает: правило может быть верным,
// а не позваться вовсе — ровно тот класс дыры, на котором проект уже обжигался (лимитер частоты был
// покрыт, а его вызов из роута не проверял никто). Здесь проверяется ШОВ.

const read = (p: string) => readFileSync(new URL(p, import.meta.url), 'utf8')
/** Исходник без комментариев: закомментированный разбор законно цитирует и прежний код, и мутации. */
const code = (p: string) => read(p).replace(/<!--[\s\S]*?-->/g, '').replace(/^\s*\/\/.*$/gm, '')

describe('#443: событие настроек меняет содержимое экрана, а не только баннер', () => {
  it('обработчик ЖДЁТ перечитывания настроек, а не запускает его фоном', () => {
    // ⚠ Мутация «вернуть `void loadSettings()`»: цель по умолчанию бралась бы из ещё не обновлённого
    // `mapping`, экран показал бы прежнее значение и остался бы с ним до следующего события — тихо
    // и правдоподобно.
    //
    // ⚠ ПЕРВАЯ РЕДАКЦИЯ ЭТОГО ТЕСТА МУТАЦИЮ ПРОПУСКАЛА, и нашёл это разбор. Позитивная проверка
    // искала `await loadSettings()` ПО ВСЕМУ ФАЙЛУ, а он есть ещё и в `onMounted` — к обработчику
    // события отношения не имеющий. Негативная была привязана к синхронной стрелке `() => {`, тогда
    // как естественная мутация выглядит иначе: стрелку оставляют `async`, а `await` меняют на
    // `void`. Тест декларировал защиту, которой не давал. Теперь утверждение делается ВНУТРИ СРЕЗА
    // самого обработчика — это и есть разница между «в файле есть нужное слово» и «оно стоит там,
    // где решает».
    const page = code('../../app/pages/app.vue')
    const handler = page.split('subscribeReload(async () => {')[1]?.split('\n})')[0] ?? ''
    expect(handler, 'обработчик события не найден — подпись изменилась').not.toBe('')
    expect(handler, 'настройки читаются фоном: цель возьмётся из устаревших').toContain('await loadSettings()')
    expect(handler).not.toContain('void loadSettings()')
  })

  it('после перечитывания новая цель передаётся карточке загрузки', () => {
    // Без этого вызова событие снимало бы только баннер «сначала настройте» — узкая цель, ради
    // которой механизм и делался, и которая перестала быть достаточной.
    const page = code('../../app/pages/app.vue')
    expect(page).toMatch(/stagingRef\.value\?\.adoptSettingsTarget\(\)/)
  })

  it('карточка загрузки действительно отдаёт этот метод наружу', () => {
    // Шов с другой стороны: `defineExpose` легко потерять при правке, и тогда вызов выше молча
    // ничего не делает — `?.` проглотит отсутствие метода.
    const staging = code('../../app/components/ImportStaging.vue')
    expect(staging).toMatch(/defineExpose\(\{ adoptSettingsTarget \}\)/)
    // И решение принимает ЧИСТОЕ правило, а не переписанное здесь условие.
    expect(staging).toMatch(/adoptDefaultTarget\(\{ importing: importing\.value \}\)/)
  })
})

describe('#443: блокировка на время пачки — настоящая, а не только для мыши', () => {
  const page = () => code('../../app/pages/app.vue')

  it('шестерёнка настроек блокируется вместе с остальным экраном', () => {
    // ⚠ Раньше блокировки у неё не было ВООБЩЕ: она живёт в слоте навбара каркаса, то есть вне всех
    // блоков, которые гасятся по `busy`. Несимметричность была невидима — обе кнопки выглядят
    // одинаково доступными, и сотрудник открывал настройки прямо посреди загрузки.
    const right = page().split('<template #right>')[1]?.split('</template>')[0] ?? ''
    expect(right, 'слот #right не найден').not.toBe('')
    expect(right).toMatch(/:disabled="busy"/)
    // Подпись меняется вместе с состоянием: отключённая кнопка без объяснения читается как поломка,
    // а программе чтения приглушённая карточка рядом ничего не сообщает.
    expect(right).toMatch(/aria-label="busy \?/)
  })

  it('`pointer-events-none` больше не используется как замок', () => {
    // ⚠ Это блокировка ТОЛЬКО ДЛЯ МЫШИ: кнопки внутри такого контейнера остаются в порядке обхода
    // по Tab и срабатывают по Enter — то есть посреди пачки счётчики можно было обнулить с
    // клавиатуры. Негативное утверждение намеренно: приём легко вернуть, он выглядит рабочим.
    expect(page()).not.toContain('pointer-events-none')
  })

  it('каждое действие под замком отключается по-настоящему — поимённо', () => {
    // ⚠ Раньше все они закрывались ОДНИМ контейнером, поэтому пропущенная кнопка не видна глазами:
    // визуально приглушено всё. Перечисляем поимённо — шесть действий в трёх блоках.
    const p = page()
    const before = (needle: string, n = 700) => p.slice(Math.max(0, p.indexOf(needle) - n), p.indexOf(needle))
    expect(before('Подробные метрики'), '«Подробные метрики» без disabled').toMatch(/:disabled="busy"/)
    expect(p, '«Сбросить» без disabled').toMatch(/label="Сбросить"[\s\S]{0,200}:disabled="busy"/)
    expect(p, '«Да, обнулить» без disabled').toMatch(/:disabled="resetting \|\| busy"/)
    expect(p, '«Очистить список» без disabled').toMatch(/label="Очистить список"[\s\S]{0,200}:disabled="busy"/)
    expect(p, '«Да, очистить» без disabled').toMatch(/label="Да, очистить"[\s\S]{0,200}:disabled="busy"/)
  })

  it('оформление осталось оформлением: приглушение есть, а `select-none` снят', () => {
    // `select-none` ехал в связке с замком и запрещал ВЫДЕЛЯТЬ ТЕКСТ — к блокировке действий это
    // отношения не имеет и мешало скопировать число из счётчиков.
    const p = page()
    expect(p).toMatch(/:class="busy \? 'opacity-60' : ''"/)
    expect(p).not.toContain('select-none')
  })
})
