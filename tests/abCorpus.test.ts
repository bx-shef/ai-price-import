import { createHash } from 'node:crypto'
import { readFileSync, readdirSync } from 'node:fs'
import { resolve } from 'node:path'
import { describe, expect, it } from 'vitest'

// Гард каталога `corpus/prompt-ab` — обезличенных документов для `pnpm ab:prompt` (#342).
//
// Зачем он нужен, хотя тестов «на данные» в проекте обычно нет: пустой или урезанный корпус
// НЕ виден по результату замера. Скрипт печатает полноценный отчёт из нулей — «итог не сошёлся:
// 0» с обеих сторон читается как «всё в порядке», хотя не измерено ничего. В самом скрипте
// стоит `throw` на пустой каталог, но он ловит только полную пропажу; исчезновение ОДНОГО файла
// (переименовали, потеряли при мерже) ничем бы не проявилось — «сколько файлов должно быть»
// знает только README.
const DIR = resolve(new URL('..', import.meta.url).pathname, 'corpus/prompt-ab')

/** ВЕСЬ листинг каталога, а не только `.txt`. Фильтр по расширению делал невидимым ровно то,
 *  чего мы боимся: необезличенный исходник (`.pdf`, `.xlsx`), брошенный сюда «попробовать
 *  локально» и уехавший в публичный репозиторий через `git add`. */
const corpusFiles = (): string[] => readdirSync(DIR).filter(f => f !== 'README.md').sort()
const readme = (): string => readFileSync(resolve(DIR, 'README.md'), 'utf8')

/** Имена файлов, упомянутые в таблице README (`| \`имя.txt\` | …`). */
const documentedFiles = (): string[] =>
  [...readme().matchAll(/^\|\s*`([^`]+\.txt)`\s*\|/gm)].map(m => m[1]!).sort()

/**
 * Нормализация для сравнения имён: только буквы и цифры, всё прочее — разделитель.
 *
 * Так снимаются сразу три способа спрятать имя, каждый из которых уже срабатывал:
 * растянутые `pdftotext -layout` пробелы («Общество   с   ограниченной …»), кавычки вокруг
 * названия и точки внутри подписи («С.С.Фамилия» → отдельное слово «фамилия»).
 */
const norm = (s: string): string =>
  s.replace(/[^0-9A-Za-zА-Яа-яЁё]+/g, ' ').replace(/\s+/g, ' ').trim().toLowerCase()

const sha = (s: string): string => createHash('sha256').update(s).digest('hex')

/**
 * Запрещённые имена — ХЭШАМИ, не открытым текстом.
 *
 * Первая редакция этого гарда держала список настоящих названий и фамилий прямо здесь, в
 * публичном репозитории — то есть чинила утечку в данных, создавая ровно такую же утечку в
 * коде. Хэш даёт то же свойство (совпадение ловится при любых пробелах и кавычках), но сам
 * ничего не раскрывает: подобрать по нему имя можно только уже зная его.
 *
 * Это заслон от ПОВТОРЕНИЯ известной ошибки, а НЕ сканер персональных данных: он знает лишь то,
 * что однажды прорвалось. Для нового документа единственная настоящая проверка — ручная сплошная
 * выгрузка имён собственных, описанная в README каталога.
 *
 * Добавить имя: посчитать `sha256` от нормализованной формы (см. `norm`) и положить сюда хэш —
 * открытый текст в этот файл не попадает никогда.
 */
const FORBIDDEN = new Set([
  '9d0bc44bf624167e5bd1ab045313ca84adc38e3a7b50f0fd34c81ade7b6840ee', // 2 слова
  'a0227e6d050bec6cd399232ab372cf5a83b3c2a19a2eec47d39f67b348e1b9ad',
  '685caa9e5972ba24650ad46d3e0353d64d42a1d1e8a83696cd80697151fa8ab2',
  '11bf39c2204c3e216166c942c2a99c11f2f207a021cced25494aedebdcabf1e8',
  '4e7bb2feaa2cf0c3e49edfcc65f9fbcf15531319a3f66665616a233a8df7f6a5',
  '7f2f1561835c56f7fe13533e2d6b4e0d8b6711134b0539a163f6b75771bf4908',
  '9b3171caceed3e95051ce08c41575034cd8e46dc009c4a9064907b0a62c1a20a', // 2 слова
  'c6e8ac954c319125c6bdf606f62c25d38f44572e3788bed505be9f3fd464feac'
])
/** Самое длинное запрещённое имя — в словах; шире окна искать незачем. */
const MAX_NAME_WORDS = 2

describe('корпус для ab:prompt', () => {
  it('в каталоге есть документы (пустой корпус даёт отчёт из нулей, а не ошибку)', () => {
    expect(corpusFiles().length).toBeGreaterThanOrEqual(5)
  })

  it('README и каталог совпадают один в один — ни лишнего файла, ни потерянного', () => {
    expect(corpusFiles()).toEqual(documentedFiles())
  })

  it('ни один документ не пустой', () => {
    for (const f of corpusFiles()) {
      expect(readFileSync(resolve(DIR, f), 'utf8').trim().length, f).toBeGreaterThan(500)
    }
  })

  // Числа таблиц — единственное, ради чего корпус существует, и обезличивание их не трогало.
  // Испортить их может любая ПОЗДНЕЙШАЯ правка (ручное редактирование, конфликт мержа, повторный
  // прогон замен). Пин на документе, чья арифметика и есть заявленный класс: тариф округлён,
  // поэтому кол-во × цена НЕ равно напечатанной сумме строки — если кто-то «поправит» 64,54 на
  // 64,90, файл перестанет проверять то, ради чего добавлен.
  it('округлённый тариф в акте цел — иначе документ перестаёт держать свой класс', () => {
    const akt = readFileSync(resolve(DIR, 'akt-uslugi-tarif-rounding.txt'), 'utf8')
    expect(akt).toMatch(/"110"\s*"0\.59"\s*"64\.54"/)
    // Две строки с ОДНОЙ парой 48,3 × 0,25 печатают разные суммы — 12,08 и 11,94.
    expect(akt).toContain('"48.3"\t"0.25"\t"12.08"')
    expect(akt).toContain('"48.3"\t"0.25"\t"11.94"')
  })

  // Пины только на одном документе оставляли остальные эталонные без защиты: «причёсывающая»
  // правка числа прошла бы молча и убила ровно то, ради чего файл добавлен.
  it('числа двух других эталонных документов целы', () => {
    // Канонический #302/#347: суб-копеечная цена × большое количество. Округление цены на
    // единицу вместо строки дало бы 10 300 вместо 10 320 — ради этого документ и добавлен.
    const sub = readFileSync(resolve(DIR, 'schet-by-subkopeck-price-big-qty.txt'), 'utf8')
    expect(sub).toMatch(/10 000 ШТ\s+0,860\s+8 600,00\s+20%\s+1 720,00\s+10 320,00/)
    expect(sub).toContain('Всего к оплате:            10 320,00')
    // Две ценовые колонки: цена за м³ рядом с количеством в упаковках. Взяв не ту пару,
    // строка вырастает в разы (2 149,63 × 32 = 68 788 против верных 46 432).
    const two = readFileSync(resolve(DIR, 'schet-ru-two-price-columns.txt'), 'utf8')
    expect(two).toMatch(/21,60\s+2 149,63\s+32\s+1 451,00\s+46 432,00/)
    expect(two).toMatch(/руб\.\/м3 с НДС/)
  })

  it('имён, которые уже один раз прорвались, в корпусе нет (при любых пробелах и кавычках)', () => {
    for (const f of corpusFiles()) {
      const words = norm(readFileSync(resolve(DIR, f), 'utf8')).split(' ')
      for (let n = 1; n <= MAX_NAME_WORDS; n++) {
        for (let i = 0; i + n <= words.length; i++) {
          const hit = FORBIDDEN.has(sha(words.slice(i, i + n).join(' ')))
          // В сообщении — ПОЗИЦИЯ, а не само слово: иначе упавший тест напечатал бы в лог CI
          // ровно то имя, которое мы отсюда убирали.
          expect(hit, `${f}: запрещённое имя, окно ${n} сл. с позиции ${i}`).toBe(false)
        }
      }
    }
  })
})
