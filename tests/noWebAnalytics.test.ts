import { readFileSync, readdirSync } from 'node:fs'
import { join } from 'node:path'
import { describe, expect, it } from 'vitest'

// Решение владельца 2026-08-04: **веб-аналитики на сайте нет и не будет** без отдельного решения.
//
// Причина не техническая, а юридическая. Счётчик собирает IP и ставит cookie — это персональные
// данные посетителя, которые собирает НЕ клиент-портал, а издатель: посетитель сайта ничего не
// устанавливал и никому поручения не давал. Значит по Закону № 99-З издатель становится ВЛАДЕЛЬЦЕМ
// персональных данных со своими обязанностями (политика обработки отдельным документом,
// ответственное лицо за внутренний контроль), а по 152-ФЗ — оператором, с уведомлением
// Роскомнадзора. Ровно тот статус, от которого основной сценарий уходит позицией «мы обработчик».
//
// Цена отказа мала: заявки с лендинга приходят формой Битрикс24 и видны в самой CRM — конверсия
// считается там, без внешнего счётчика. Цена подключения — постоянная юридическая нагрузка на
// продукт, который на этом не зарабатывает.
//
// ⚠ Гард сторожит ИМЕННО ЭТО, а не «нет строки metrika»: подключить счётчик можно тремя разными
// способами (id в рантайм-конфиге, инлайн-сниппет в `nuxt.config`, скрипт в `public/`), и запрет
// одного из них ничего не гарантирует. Проверяются все три плюс CSP: разрешённый в политике
// безопасности хост аналитики — первый признак, что счётчик собираются вернуть.
//
// Подключение возможно, но не «заодно»: сначала новая редакция Политики конфиденциальности сайта
// (раздел 5), потом код. Обратный порядок означает месяц обработки данных вопреки опубликованному
// документу — тот же капкан, что описан в задаче про резервные копии.

const ROOT = new URL('..', import.meta.url).pathname
const read = (p: string) => readFileSync(join(ROOT, p), 'utf8')

/** Хосты известных счётчиков. Список именной: новый сервис — отдельное решение, а не молчаливый add. */
const ANALYTICS_HOSTS = ['mc.yandex.ru', 'mc.yandex.com', 'google-analytics.com', 'googletagmanager.com', 'top-fwz1.mail.ru']

describe('веб-аналитики на сайте нет (решение владельца, #297)', () => {
  it('идентификатор счётчика в конфиге пуст', () => {
    const config = read('nuxt.config.ts')
    // Пустая строка — не «забыли заполнить», а действующее решение. Непустое значение включает
    // счётчик в проде и делает раздел 5 Политики сайта описанием реальности, которой сейчас нет.
    expect(config).toMatch(/metrikaId:\s*''/)
  })

  it('в разметке и конфиге нет инлайн-сниппета счётчика', () => {
    // Второй способ: сниппет прямо в `app.head.script` — тогда пустой id ничего не значит.
    for (const f of ['nuxt.config.ts', 'app/app.vue']) {
      const src = read(f)
      expect(src, `${f}: сниппет счётчика`).not.toMatch(/ym\(\s*\d|mc\.yandex|gtag\(|dataLayer/)
    }
  })

  it('в public/ нет скрипта счётчика', () => {
    // Третий способ: файл в `public/`, подключённый тегом. Он вне сборки и мимо ревью Vue-кода.
    for (const name of readdirSync(join(ROOT, 'public'))) {
      if (!name.endsWith('.js') && !name.endsWith('.html')) continue
      const src = read(`public/${name}`)
      for (const host of ANALYTICS_HOSTS) {
        expect(src, `public/${name}: ${host}`).not.toContain(host)
      }
    }
  })

  it('CSP не разрешает хосты аналитики — ни в nginx, ни в app-level', () => {
    // Самый честный признак намерения: счётчик без разрешения в CSP не заработает, поэтому хост
    // в политике появляется РАНЬШЕ самого счётчика. Здесь запрет и срабатывает первым.
    for (const f of ['nginx.conf', 'server/utils/edgeSecurity.ts']) {
      const src = read(f)
      for (const host of ANALYTICS_HOSTS) {
        expect(src, `${f}: ${host} разрешён в CSP`).not.toContain(host)
      }
    }
  })
})
