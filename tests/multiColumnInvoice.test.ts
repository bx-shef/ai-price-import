import { describe, it, expect } from 'vitest'
import { describeTotalMismatch, findTotalGapSuspect, pricingTolerance, reconcilePricing } from '../app/utils/pricing'

// ⚠ Ветка «пропавшая строка» здесь НЕ дублируется: она уже закреплена в `tests/pricing.test.ts`
// (блок #336), и вторая копия расходилась бы с первой при первой же правке допуска.

// #442: счёт РБ, где в строке товара СЕМЬ числовых колонок подряд, и между отпускной ценой и ценой
// стоит ПРОЦЕНТ НАДБАВКИ, по величине сравнимый с ценой (11,61 против 3,75). Глазами колонки
// различает шапка; в тексте после распознавания они идут подряд, и перепутать их легко.
//
// Зачем эти тесты, если сам разбор здесь не участвует. Живой прогон владельца дал на таком счёте
// два дефекта извлечения, и первый вопрос разбора — не «как поправить промпт», а **сработали ли
// наши сети**. Оказалось, что да: флаг НДС чинится сам, а подмена колонки даёт расхождение итогов
// и предупреждение человеку. Это поведение не было закреплено НИГДЕ — то есть следующая правка
// сверки могла бы его снять, и мы бы узнали об этом от клиента, а не от CI.
//
// ⚠ Числа взяты ИЗ ТЕЛА issue (там они уже обезличены) и сокращены до двух показанных строк с
// пересчитанными под них итогами: Итого 52,00 · НДС 20% 10,40 · Всего к оплате 62,40. Класть сюда
// клиентский документ нельзя — репозиторий публичный.
//
// ⚠ Эти тесты НЕ утверждают, что документ разберётся правильно. Они утверждают ровно то, что
// проверено: если модель ошибётся ИМЕННО ТАК, человек об этом узнает. Точность самого извлечения —
// вопрос промпта и замера на внешнем корпусе (см. #442), и подменять одно другим нельзя.

/** Строка счёта: количество 2, НДС 20% — как в документе. */
const line = (name: string, price: number) => ({ name, quantity: 2, price, vatRate: 20 })

/** «Всего к оплате с НДС» — то, что напечатано внизу документа. */
const PRINTED_TOTAL = 62.40

/**
 * Поиск подозреваемой строки — ровно с теми аргументами, что в бою (`crmSyncCore`).
 *
 * ⚠ Обёртка не косметическая: сигнатура `(items, РАЗНИЦА, inclusive, допуск)` легко читается как
 * `(items, итог, итог, флаг)`, и именно так я её и вызвал в первой редакции — получил `null`,
 * принял за поведение кода и едва не записал в тест неверное утверждение. Здесь вызов один и он
 * повторяет боевой.
 */
const suspectOf = (items: ReturnType<typeof line>[], grossTotal: number) =>
  findTotalGapSuspect(items, grossTotal - PRINTED_TOTAL, false, pricingTolerance(items.length, PRINTED_TOTAL))

describe('#442: счёт с процентом надбавки между ценовыми колонками', () => {
  it('модель сказала «цены с НДС», а они без НДС — флаг чинится САМ, итог верный', () => {
    // Самый частый крен модели на этом классе. Структура итогов однозначна: Итого → Сумма НДС →
    // Всего к оплате, и Σ(цена×кол)+НДС сходится с печатным итогом, а Σ(цена×кол) — нет.
    const r = reconcilePricing([line('А', 3.75), line('Б', 22.25)], true, PRINTED_TOTAL)
    expect(r.priceIncludesVat, 'нетто-документ обязан читаться как нетто').toBe(false)
    expect(r.corrected, 'исправление флага — наблюдаемый факт, а не побочный эффект').toBe(true)
    expect(r.grossTotal).toBe(62.40)
    expect(r.totalMismatch).toBe(false)
  })

  it('⚠ обратный крен НЕ ловится, и это записано, а не забыто', () => {
    // `reconcilePricing` правит флаг ТОЛЬКО в сторону «без НДС» и обратно не флипает — иначе
    // честно валовый документ раздувался бы на ставку НДС. Значит документ, где цены ДЕЙСТВИТЕЛЬНО
    // с НДС, а модель сказала «без НДС», уедет с задвоенным налогом, и ни одна сеть не сработает.
    // Тест фиксирует границу защиты: чинить это можно только точностью извлечения.
    const r = reconcilePricing([line('А', 4.50)], false, 9.00)
    expect(r.priceIncludesVat).toBe(false)
    expect(r.corrected).toBe(false)
  })

  it('за цену принят процент надбавки → расхождение итогов и предупреждение человеку', () => {
    // 2×11,61 + 2×9,07 = 41,36 против печатных 62,40. Ни одно прочтение НДС этого не объясняет.
    const items = [line('А', 11.61), line('Б', 9.07)]
    const r = reconcilePricing(items, false, PRINTED_TOTAL)
    expect(r.totalMismatch, 'подмена колонки обязана быть замечена').toBe(true)
    expect(r.usedStatedTotal, 'печатному итогу тут верить нельзя — он не сошёлся').toBe(false)

    const suspect = suspectOf(items, r.grossTotal)
    const text = describeTotalMismatch(PRINTED_TOTAL, r.grossTotal, 'BYN', suspect, suspect ? items[suspect.index]?.name : undefined)
    // Названы ТРИ числа: что напечатано, что вышло у нас, и разница. Без них человеку нечего
    // сверять — «суммы не сошлись» не подсказывает следующего шага.
    expect(text).toContain('62,40')
    expect(text).toContain('49,63')
    expect(text).toContain('12,77')
  })

  it('⚠ НЕВЕРНАЯ ЦЕНА конкретной строки подсказкой не находится — и это по построению', () => {
    // Разбор ревью: `findTotalGapSuspect` ищет ПРОПАВШУЮ СТРОКУ («разница равна одной строке
    // целиком») либо ПОТЕРЯННОЕ КОЛИЧЕСТВО. Неверно прочитанная ценовая колонка под эти формы не
    // подходит: разница равна не сумме строки, а её ЧАСТИ, и объяснить её можно бесконечным числом
    // способов. Поэтому здесь человек получает три числа и общий совет — это честный предел
    // подсказки, а не недоделка.
    //
    // ⚠ Тест держит границу с ДВУХ сторон: одна ошибочная цена (ниже) и две (в предыдущем тесте)
    // одинаково дают `null`. Пока это так, «строку не назвали» нельзя прочитать как «строка одна и
    // мы её нашли».
    const one = [line('А', 3.75), line('Б', 9.07)] // вторая — процент вместо цены 22,25
    const r1 = reconcilePricing(one, false, PRINTED_TOTAL)
    expect(r1.totalMismatch).toBe(true)
    expect(suspectOf(one, r1.grossTotal)).toBeNull()

    const both = [line('А', 11.61), line('Б', 9.07)]
    const r2 = reconcilePricing(both, false, PRINTED_TOTAL)
    expect(suspectOf(both, r2.grossTotal)).toBeNull()
  })

  it('счёт целиком верен → ни расхождения, ни предупреждения', () => {
    // Инвариант в обратную сторону: сеть, которая срабатывает на исправном документе, хуже, чем
    // её отсутствие — человек перестаёт читать предупреждения через неделю.
    const r = reconcilePricing([line('А', 3.75), line('Б', 22.25)], false, PRINTED_TOTAL)
    expect(r.totalMismatch).toBe(false)
    expect(r.grossTotal).toBe(62.40)
  })
})
