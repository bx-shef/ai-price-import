import { readFileSync } from 'node:fs'
import { describe, expect, it } from 'vitest'
import { allLinesSkippedError } from '../app/utils/importOutcome'

// Один инвариант на ТРИ места (#459 + отсмотр #385).
//
// С #459 карточка создаётся ВСЕГДА, включая неудачную загрузку: без неё у дела нет владельца, а без
// дела импорт не попадает в журнал — то есть загрузка не оставила бы следа ровно в том случае, ради
// которого в журнал заходят. Поведение изменилось, а тексты о нём — нет, и три разных места
// продолжали обещать, что «запись в CRM не создана»:
//
//   • `app/utils/importOutcome.ts` — текст отказа, уходит в чат и в результат;
//   • `app/pages/app.vue`          — предупреждение о выбранной настройке на рабочем экране;
//   • `app/components/SettingsForm.vue` — подсказка под тем же полем в настройках (форма уехала
//     из `app/pages/settings.vue` в #523; проверка сторожит ТЕКСТ, а не место, поэтому просто
//     читает тот файл, где он теперь живёт).
//
// ⚠ Первые два нашёл владелец на живом портале, ТРЕТЬЕ — только сплошной обход: точечная правка «по
// указанию» закрыла два и оставила третье, а оно дало бы четвёртый заход. Отсюда этот гард: он
// заявлен над ВСЕМИ местами сразу, а не над каждым по отдельности, потому что дефект был не в
// формулировке, а в том, что копии разъехались с поведением поодиночке и молча.
//
// ⚠ Утверждение об отсутствии записи опаснее умолчания: по нему НЕ ИДУТ ПРОВЕРЯТЬ. Человек,
// прочитавший «запись не создана», не пойдёт искать в воронке карточку, которая там лежит.

const SOURCES = [
  'app/utils/importOutcome.ts',
  'app/pages/app.vue',
  'app/components/SettingsForm.vue'
] as const

/** Текст без комментариев: закомментированный разбор законно цитирует прежнюю неправду. */
function userText(rel: string): string {
  const raw = readFileSync(new URL(`../${rel}`, import.meta.url), 'utf8')
  return raw
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/^\s*\/\/.*$/gm, '')
}

describe('#459: тексты не обещают, что записи в CRM не будет', () => {
  for (const rel of SOURCES) {
    it(`${rel} не утверждает «запись не создана/не создастся»`, () => {
      const text = userText(rel)
      // ⚠ Ищем именно связку «запись/сущность/карточка … не создан…», а не голое «не создан»:
      // соседние законные фразы («не созданные карточки», «Сущность не создана» в контексте отзыва)
      // не должны красить гард — иначе его отключат вместо того, чтобы чинить дефект.
      expect(text, 'осталось обещание, что записи в CRM не будет')
        .not.toMatch(/(запис[ьи]|сущност[ьи]|карточк[аи])[^.\n]{0,40}не\s+созда/i)
    })
  }

  it('все три места говорят про ПУСТУЮ карточку — одинаковым словом', () => {
    // ⚠ Проверяется не совпадение формулировок (они разные по месту и это нормально), а то, что ни
    // одно из трёх не молчит о следствии: пустая карточка с нулевой суммой остаётся в воронке
    // клиента и искажает его отчёты по обороту. Молчание об этом и было второй половиной дефекта.
    // ⚠ Форма глагола НЕ фиксируется: в отказе «карточка создана» (уже случилось), в предупреждении
    // «карточка создастся» (ещё нет). Требовать одно написание значило бы требовать неверный текст
    // в одном из мест — гард обязан описывать смысл, а не букву.
    for (const rel of SOURCES) {
      expect(userText(rel), `${rel} молчит о пустой карточке`)
        .toMatch(/карточк\w*[^.\n]{0,30}пуст|пуст\w*[^.\n]{0,30}карточк/i)
    }
  })

  it('текст отказа согласован с разметкой — он и есть источник формулировки', () => {
    // Шов: сама функция под тестом отдельно, но если её текст разойдётся с экранами, человек
    // прочтёт в чате одно, а в настройках другое об одном и том же исходе.
    expect(allLinesSkippedError(2)).toMatch(/карточка создана пустой/i)
    expect(allLinesSkippedError(2)).not.toMatch(/не\s+созда/i)
  })

  it('«отклонены целиком» не вернулось — пропускается СТРОКА, а не документ', () => {
    // Отдельная неправда того же предупреждения: отказ наступает лишь когда не нашлась НИ ОДНА
    // позиция, а не на каждом документе без артикулов.
    for (const rel of SOURCES) {
      expect(userText(rel), rel).not.toMatch(/отклонен[ыо]\s+целиком|отклонён\s+целиком/i)
    }
  })
})
