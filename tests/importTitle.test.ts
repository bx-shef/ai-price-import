import { readFileSync } from 'node:fs'
import { describe, expect, it } from 'vitest'
import { buildImportTitle, supplierNameTrusted } from '../app/utils/importTitle'

// #440. Заголовок записи — не предупреждение, которое прочитали и забыли: он становится ИМЕНЕМ
// ЗАПИСИ В CRM КЛИЕНТА НАВСЕГДА и попадает в списки, поиск и отчёты. Раньше туда безусловно шло
// распознанное название поставщика, в том числе когда модель не нашла в шапке даже налоговый
// номер — то есть когда шапка, скорее всего, не прочиталась вовсе.

describe('#440: название поставщика в заголовке — только при распознанном налоговом номере', () => {
  it('номер распознан → название в заголовке, как и было', () => {
    expect(buildImportTitle({ supplier: { name: 'ООО «Ромашка»', taxId: '191234567' } })).toBe('Импорт: ООО «Ромашка»')
  })

  it('номера нет → названия в заголовке НЕТ', () => {
    // Несущее утверждение задачи. Мутация «писать имя всегда» обязана краснеть здесь.
    const t = buildImportTitle({ supplier: { name: 'ООО «Ромашка»' }, documentType: 'счёт' })
    expect(t).not.toContain('Ромашка')
    expect(t).toBe('Импорт: счёт')
  })

  it('«компания не найдена» — НЕ повод прятать название: номер-то распознан', () => {
    // ⚠ Два разных состояния, и правка касается только одного. Номер на месте ⇒ шапка прочитана ⇒
    // название почти наверняка верное, а компании с таким номером в CRM просто ещё нет: это новый
    // контрагент, и имя — единственная зацепка для менеджера. Функция о поиске в CRM не знает
    // вовсе, и это защита от того, чтобы правку однажды «дообобщили».
    expect(buildImportTitle({ supplier: { name: 'ООО «Новый»', taxId: '100000000' } })).toContain('ООО «Новый»')
  })

  it('запасной заголовок различим в списке, а не «Импорт: документ» пятьюдесятью строками', () => {
    // ⚠ Тип и сумма взяты из самого документа: их видно глазами на бумаге, они проверяемы.
    // ⚠ Разделитель разрядов — неразрывный пробел из `toLocaleString('ru-RU')`; обычный в сравнении
    // не совпадёт, и это правильное написание, а не то, что надо чинить.
    expect(buildImportTitle({ supplier: { name: 'кто-то' }, documentType: 'счёт', total: 10320, currency: 'BYN' }))
      .toMatch(/^Импорт: счёт на 10\s320,00 BYN$/)
    // Нет суммы — часть опускается целиком, а не печатается пустой.
    expect(buildImportTitle({ documentType: 'накладная' })).toBe('Импорт: накладная')
    // Нет вообще ничего — честный запасной вариант.
    expect(buildImportTitle({})).toBe('Импорт: документ')
  })

  it('пустые и пробельные значения считаются отсутствующими', () => {
    // Модель вправе вернуть пустую строку вместо пропуска поля; без trim заголовок стал бы
    // «Импорт:  » — то есть визуально сломанным именем записи.
    expect(supplierNameTrusted({ supplier: { name: '  ', taxId: '191234567' } })).toBeNull()
    expect(supplierNameTrusted({ supplier: { name: 'ООО «Ромашка»', taxId: '  ' } })).toBeNull()
    expect(buildImportTitle({ supplier: { name: '  ', taxId: '1' }, documentType: '  ' })).toBe('Импорт: документ')
  })

  it('заголовок капнут в ОБЕИХ ветках — портал режет поле, а его обрезка непредсказуема', () => {
    expect(buildImportTitle({ supplier: { name: 'Я'.repeat(400), taxId: '1' } })).toHaveLength(255)
    // ⚠ И в запасной тоже: `documentType` приходит от модели (валидатор пропускает до 120 знаков),
    // то есть заголовок, придуманный ИЗ-ЗА недоверия к чтению, сам бы из него и вылезал за поле.
    expect(buildImportTitle({ documentType: 'Я'.repeat(400) }).length).toBeLessThanOrEqual(255)
  })

  it('тип документа сверяется с закрытым списком, а не берётся как есть', () => {
    // ⚠ `validateExtractedDocument` принимает в это поле ЛЮБУЮ строку до 120 знаков. Без сверки
    // запасной заголовок целиком состоял бы из нефильтрованного текста модели: на криво прочитанной
    // шапке вышло бы «Импорт: Счёт-фактура № 12/… на …» — ровно то, от чего заголовок и уводят.
    expect(buildImportTitle({ documentType: 'Счёт-фактура № 12/44 от 03.08' })).toBe('Импорт: документ')
    expect(buildImportTitle({ documentType: 'накладная' })).toBe('Импорт: накладная')
  })

  it('нечисловая сумма не печатается в имя записи', () => {
    // ⚠ «Импорт: счёт на NaN» осталось бы именем записи в CRM навсегда.
    for (const bad of [Number.NaN, Number.POSITIVE_INFINITY]) {
      expect(buildImportTitle({ documentType: 'счёт', total: bad, currency: 'BYN' })).toBe('Импорт: счёт')
    }
  })

  it('сумма в заголовке — та, что уйдёт в запись, а не печатный итог документа', () => {
    // ⚠ Расходятся они штатно: нетто-счёт с напечатанным «Итого 8 600» (субтотал без НДС) создаёт
    // сделку на 10 320, а частичная запись даёт сумму только записанных строк. Заголовок с печатным
    // итогом навсегда назвал бы запись числом, которого в ней нет, — то самое расхождение «шапка
    // против вкладки товаров», ради которого писались #302 и #347, только теперь в имени записи.
    const t = buildImportTitle({ documentType: 'счёт', total: 8600, currency: 'BYN' }, 10320)
    expect(t).toMatch(/10\s320,00/)
    expect(t).not.toContain('8')
  })

  it('поле лида `companyTitle` подчиняется ТОМУ ЖЕ правилу', () => {
    // ⚠ Там непроверенное название становится не подписью, а полем ДАННЫХ карточки — то есть хуже
    // заголовка. Два независимых условия разъехались бы, и имя, не попавшее в заголовок, всё равно
    // оказалось бы в карточке. Проверяем по проводке, что обе точки читают одну функцию.
    const src = readFileSync(new URL('../server/queue/crmSyncCore.ts', import.meta.url), 'utf8')
      .replace(/\/\/.*$/gm, '')
    // ⚠ Греп сторожит вызов И его аргумент: без второго проверка пропускала бы пост-обработку
    // («…».replace(...)) и подстановку имени обратно — то есть отмену правки при зелёном тесте.
    // ⚠ У заголовка ДВЕ ветки (#459): удачная загрузка идёт общим правилом, неудачная получает
    // «Импорт не удался» — по нему такие карточки отличают в списке сущностей. Гард сторожит
    // именно удачную ветку: подмена её на что-то своё и есть отмена правила.
    expect(src, 'заголовок собирается мимо общего правила').toMatch(/: buildImportTitle\(doc, opportunityValue\),/)
    expect(src, 'результат заголовка постобрабатывается').not.toMatch(/buildImportTitle\([^)]*\)\s*[.+]/)
    expect(src, 'companyTitle заполняется мимо общего правила').not.toMatch(/companyTitle:\s*doc\.supplier/)
    // Имя вычисляется ОДИН раз и переиспользуется — повторный вызов с `!` ломался бы молча.
    expect(src).toMatch(/const trustedSupplierName = supplierNameTrusted\(doc\)/)
    expect(src).toMatch(/companyTitle:\s*trustedSupplierName/)
  })
})
