import { describe, expect, it } from 'vitest'
import { readFileSync } from 'node:fs'
import { resolve } from 'node:path'

// #493. Срок жизни записи задания — решение владельца 10.08.2026 («пусть много не живёт»), и оно
// про данные клиента: имя файла, идентификатор загрузившего и выбранную цель мы держим у себя
// ровно столько, сколько нужно на обработку.
//
// ⚠ Разбор показал, что возврат прежних 48 часов не ловил НИ ОДИН тест — а это молчаливое
// увеличение срока хранения чужих данных, то есть ровно то, что должно краснеть.
describe('#493: срок жизни записи задания', () => {
  it('по умолчанию 6 часов, а не прежние 48', () => {
    const src = readFileSync(resolve(import.meta.dirname, '..', 'server/utils/jobStore.ts'), 'utf8')
    // Дефолт читается из исходника, а не из импортированной константы: значение вычисляется на
    // загрузке модуля из переменной окружения, и в прогоне с чужим `.env` тест проверял бы среду.
    expect(src).toMatch(/Number\.isFinite\(h\) && h > 0 \? Math\.min\(h, 720\) : 6/)
  })

  it('срок продлевается на КАЖДОЙ записи, иначе он означал бы «от создания»', () => {
    // ⚠ Несущее для короткого срока: запись обновляется на каждой смене статуса, поэтому шесть
    // часов это шесть часов ТИШИНЫ, а не общий срок жизни задания. Без продления долгая очередь
    // стирала бы запись под идущей обработкой.
    const redis = readFileSync(resolve(import.meta.dirname, '..', 'server/utils/jobStoreRedis.ts'), 'utf8')
    const put = redis.slice(redis.indexOf('async put('), redis.indexOf('async getAll('))
    expect(put).toContain('pexpire')
  })
})
