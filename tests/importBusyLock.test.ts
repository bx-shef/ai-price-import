import { readFileSync } from 'node:fs'
import { describe, expect, it } from 'vitest'

// #475. Пока идёт пачка, остальной экран обязан быть заблокирован — чтобы оператор не почистил
// историю, не обнулил метрики и не открыл настройки посреди прогона.
//
// ⚠ Замок был сделан классом `pointer-events-none` на контейнере, и это НЕ блокировка: он гасит
// только указатель, а кнопки внутри остаются в порядке обхода по Tab и срабатывают по Enter. То
// есть все перечисленные действия во время пачки выполнялись с клавиатуры — ровно те, ради запрета
// которых замок и ставили. Шестерёнка настроек не была заблокирована ВООБЩЕ: она живёт в слоте
// `#right` навбара каркаса, то есть вне всех блоков, которые гасились по `busy`.
//
// ⚠ ПЕРВАЯ РЕДАКЦИЯ ЭТОГО ГАРДА САМА УТВЕРЖДАЛА НЕПРАВДУ, и это стоит помнить. Она проверяла две
// кнопки из семи, а в комментарии значилось «`pointer-events-none` больше не используется как
// замок… осталось ровно одно вхождение, и то на неинтерактивной обёртке». На деле оставались ТРИ
// вхождения в `app.vue`, два из них поверх живых кнопок («Очистить список», «Да, очистить»,
// «Сбросить», «Да, обнулить»), а вхождение в `ImportStaging` — это дропзона с обработчиками, а не
// обёртка списка. Гард, описывающий несуществующее состояние, хуже отсутствующего: он закрывает
// вопрос, не закрыв дефект. Поэтому теперь кнопки перечислены ПОИМЁННО.
//
// ⚠ ПОЧЕМУ ГАРД СТРУКТУРНЫЙ. Поведение проверяется там, где компонент монтируется по-настоящему:
// `tests/nuxt/targetPicker.nuxt.test.ts` (кнопки и оба списка выключены нативным `disabled`; плюс
// реакция на внешнюю смену цели) и `tests/nuxt/importStaging.nuxt.test.ts` (цель пачки не меняется
// после старта) — все прогнаны мутациями. Страница `app.vue` в наборе не монтируется нигде, и
// поднимать её ради семи кнопок значило бы застабить полтора десятка композаблов, то есть проверять
// не её. Здесь сторожится связь каждой кнопки с `busy` ПО ЭЛЕМЕНТУ, а не вхождение строки в файл.

const PAGE = new URL('../app/pages/app.vue', import.meta.url).pathname
const src = readFileSync(PAGE, 'utf8')

/** Вырезать разметку одного элемента по опорной строке внутри него. */
function elementAround(marker: string): string {
  const at = src.indexOf(marker)
  expect(at, `опорная строка не найдена: ${marker}`).toBeGreaterThan(-1)
  const open = src.lastIndexOf('<', at)
  const close = src.indexOf('>', at)
  expect(close).toBeGreaterThan(open)
  return src.slice(open, close + 1)
}

/**
 * Все действия, недоступные во время пачки, — поимённо.
 *
 * ⚠ Список исчерпывающий по построению: он покрывает КАЖДЫЙ интерактивный элемент внутри блоков,
 * гасимых по `busy`, плюс шестерёнку, которая живёт вне них. Новый элемент в этих блоках обязан
 * попасть сюда явно — иначе он повторит историю «замок есть, а действие проходит».
 */
const BLOCKED = [
  { what: 'шестерёнка настроек', marker: ':icon="SettingsIcon"' },
  { what: '«Подробные метрики»', marker: '@click="openMetrics"' },
  { what: '«Очистить список»', marker: 'label="Очистить список"' },
  { what: '«Да, очистить»', marker: '@click="doClearList"' },
  { what: '«Сбросить» счётчики', marker: 'label="Сбросить"' },
  { what: '«Да, обнулить»', marker: '@click="doReset"' },
  { what: 'обновление списка', marker: '@click="refreshNow"' }
]

describe('#475: блокировка экрана на время пачки — настоящая, а не косметическая', () => {
  it.each(BLOCKED)('$what выключается на время импорта', ({ marker }) => {
    expect(elementAround(marker)).toMatch(/:disabled="busy(\s*\|\|[^"]*)?"/)
  })

  it('замок НЕ держится на pointer-events-none ни в одном блоке', () => {
    // Негативная половина, и теперь она смотрит туда, где дыра и была. Класс сам по себе не
    // запрещён (на лендинге он декоративный) — запрещена связка «гасим по busy указателем».
    expect(src).not.toMatch(/busy \?[^"]*pointer-events-none/)
  })

  it('причина сказана ВИДИМОЙ строкой, а не только подсказкой у кнопки', () => {
    // ⚠ `title` на выключенной кнопке не всплывает: Chromium не доставляет отключённым контролам
    // событий указателя, а из обхода по Tab она уже выпала — то есть ни мышь, ни клавиатура причину
    // не получили бы. Носитель — баннер прогона, один на все выключенные действия.
    const staging = readFileSync(new URL('../app/components/ImportStaging.vue', import.meta.url).pathname, 'utf8')
    expect(staging).toContain('Пока идёт импорт, настройки, метрики и очистка списка недоступны.')
  })

  it('у шестерёнки одна формулировка на подпись и подсказку', () => {
    // Разойдясь, они озвучивали бы программе чтения одно, а мыши показывали другое.
    const gear = elementAround(':icon="SettingsIcon"')
    expect(gear).toContain(':aria-label="busy ? SETTINGS_BLOCKED_LABEL')
    expect(gear).toContain(':title="busy ? SETTINGS_BLOCKED_LABEL')
  })
})
