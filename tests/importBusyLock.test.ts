import { readFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { describe, expect, it } from 'vitest'

/**
 * Замок экрана на время пачки — НАСТОЯЩИЙ, а не только для мыши (#443/#475).
 *
 * ⚠ Гард восстановлен 10.08.2026 при разведении документации (#490). Прежний жил в
 * `tests/nuxt/settingsSyncWiring.nuxt.test.ts` и уехал вместе с этим файлом, когда #489 снял
 * механизм отсрочки настроек. Уехал он **сопутствующим ущербом**: к отсрочке эти проверки отношения
 * не имели. `CLAUDE.md` при этом продолжал утверждать «блокируется действие, а не выход из него», то
 * есть документ пережил свой гард — ровно тот класс расхождения, ради которого затевался #490.
 *
 * ⚠ Почему проверяется именно `:disabled`, а не `pointer-events-none`. Второе блокирует ТОЛЬКО мышь:
 * кнопка внутри такого контейнера остаётся в порядке обхода по Tab и срабатывает по Enter. Так
 * посреди пачки можно было обнулить счётчики экономии с клавиатуры. Мутация «вернуть
 * `pointer-events-none` вместо `:disabled`» обязана краснеть.
 *
 * ⚠ Проверка структурная (по шаблону SFC), а не поведенческая, и это осознанный размен: смонтировать
 * `/app` целиком нельзя без фрейм-токена, тринадцати композаблов и портала. Зато мутации, которые
 * она ловит, — это ровно те, что случались: снять `:disabled`, подменить `busy` на `loading`,
 * заменить настоящий замок оформлением.
 */

const ROOT = new URL('..', import.meta.url).pathname
const page = readFileSync(resolve(ROOT, 'app/pages/app.vue'), 'utf8')
// ⚠ Комментарии вырезаются ПЕРЕД сопоставлением: в шаблоне два пояснения, почему `pointer-events-none`
// здесь не годится, и гард, краснеющий на объяснении дефекта, подталкивает удалить объяснение, а не
// дефект. Тот же приём уже применён в гардах имени продукта и оболочки лендинга.
const template = page.slice(page.indexOf('<template>')).replace(/<!--[\s\S]*?-->/g, '')

/** Разрушительные действия, которые обязаны гаснуть на время пачки. Список ПОИМЁННЫЙ: «проверить,
 *  что где-то есть :disabled="busy"» проходило бы и когда половина кнопок его потеряла. */
// ⚠ «Очистить список» и «Да, очистить» ушли из списка вместе с самими кнопками (#479, решение
// владельца 10.08.2026): убирать строки из ленты больше нечем — история живёт в делах портала.
// Гард на несуществующую кнопку не защищает ничего, зато краснеет вечно; при этом падал он с
// ВЕРНЫМ текстом («сторожит несуществующую кнопку») — именно так эта правка и была замечена.
const LOCKED_BY_BUSY = [
  'Настройки импорта', // шестерёнка: открыть настройки посреди пачки — сменить цель на середине
  'Подробные метрики', // уводит с экрана, на котором идёт пачка и который нельзя закрывать
  'Сбросить',
  'Да, обнулить'
]

/**
 * Тег, ВНУТРИ которого стоит подпись: от ближайшего `<` слева до закрытия этого тега.
 *
 * Подпись бывает и атрибутом (`label="Сбросить"`), и текстом узла (`Подробные метрики →`), поэтому
 * границу ищем в обе стороны и берём ближайшую.
 */
function ownTag(at: number): string {
  const open = template.lastIndexOf('<', at)
  const selfClose = template.indexOf('/>', open)
  const close = template.indexOf('>', at)
  const end = selfClose > -1 && selfClose < close ? selfClose : close
  return template.slice(open, end + 1)
}

describe('#443/#475: экран на время пачки блокируется по-настоящему', () => {
  it('замок не держится на `pointer-events-none` — это блокировка только для мыши', () => {
    // `opacity` как ОФОРМЛЕНИЕ разрешена и остаётся; запрещён именно замок указателем.
    expect(template).not.toMatch(/pointer-events-none/)
  })

  for (const label of LOCKED_BY_BUSY) {
    it(`«${label}» гаснет по busy`, () => {
      // ⚠ Берём РОВНО СВОЙ тег, а не окно вокруг подписи. Окно ±700 знаков было тем же классом
      // слабого гарда, что и сам дефект #475: мутация «снять `:disabled` с „Подробные метрики“»
      // проходила мимо него — атрибут находился у СОСЕДНЕЙ кнопки в той же карточке. Гард сторожил
      // присутствие строки где-то рядом, а не блокировку названной кнопки.
      const at = template.indexOf(label)
      expect(at, `подписи «${label}» на экране нет — гард сторожит несуществующую кнопку`).toBeGreaterThan(-1)
      const tag = ownTag(at)
      expect(tag, `«${label}» должна нести :disabled c busy`).toMatch(/:disabled="[^"]*busy[^"]*"/)
    })
  }

  it('шестерёнка объявляет причину блокировки голосом, а не только гаснет', () => {
    // Погасшая кнопка без объяснения для скринридера — просто пропавшее действие.
    expect(template).toMatch(/:aria-label="busy \?/)
  })

  it('«Отмена» подтверждения по busy НЕ гаснет — блокируется действие, а не выход из него', () => {
    // ⚠ Несущее. Погасив «Отмену» заодно со «Да, обнулить», мы заперли бы человека в подтверждении
    // до конца пачки: согласиться нельзя, отказаться нельзя. Выход обязан оставаться живым.
    const at = template.indexOf('label="Отмена"')
    expect(at, 'кнопки «Отмена» на экране нет').toBeGreaterThan(-1)
    // ⚠ Берём РОВНО СВОЙ тег, а не окно вокруг подписи: соседняя «Да, обнулить» гаснет по busy
    // законно, и окно поймало бы её атрибут вместо нашего.
    expect(ownTag(at), '«Отмена» не должна гаснуть по busy').not.toMatch(/:disabled="[^"]*busy[^"]*"/)
  })

  it('причина названа СЛОВАМИ, а не только приглушением (#475)', () => {
    // Выключенная кнопка без объяснения неотличима от сломанной. Строка появляется по `busy`, стоит
    // рядом с погасшими кнопками и объявляется голосом (`role="status"`).
    const at = template.indexOf('Пока идёт загрузка, счётчики не меняем')
    expect(at, 'объяснения выключенного состояния на экране нет').toBeGreaterThan(-1)
    const window = template.slice(Math.max(0, at - 300), at)
    expect(window, 'объяснение обязано появляться именно на время пачки').toMatch(/v-if="busy"/)
    expect(window, 'смена состояния объявляется голосом').toMatch(/role="status"/)
  })
})
