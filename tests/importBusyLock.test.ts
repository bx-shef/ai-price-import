import { readFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { describe, expect, it } from 'vitest'

/**
 * Замок экрана на время пачки — НАСТОЯЩИЙ, а не только для мыши (#443/#475).
 *
 * ⚠ Гард восстановлен 10.08.2026 при разведении документации (#490). Прежний жил в
 * `tests/nuxt/settingsSyncWiring.nuxt.test.ts` и уехал вместе с этим файлом, когда #489 снял
 * механизм отсрочки настроек. Уехал он **сопутствующим ущербом**: к отсрочке эти проверки отношения
 * не имели. `CLAUDE.md` при этом продолжал утверждать «блокируется действие, а не выход из него», то
 * есть документ пережил свой гард — ровно тот класс расхождения, ради которого затевался #490.
 *
 * ⚠ Почему проверяется именно `:disabled`, а не `pointer-events-none`. Второе блокирует ТОЛЬКО мышь:
 * кнопка внутри такого контейнера остаётся в порядке обхода по Tab и срабатывает по Enter. Так
 * посреди пачки можно было обнулить счётчики экономии с клавиатуры. Мутация «вернуть
 * `pointer-events-none` вместо `:disabled`» обязана краснеть.
 *
 * ⚠ Проверка структурная (по шаблону SFC), а не поведенческая, и это осознанный размен: смонтировать
 * `/app` целиком нельзя без фрейм-токена, тринадцати композаблов и портала. Зато мутации, которые
 * она ловит, — это ровно те, что случались: снять `:disabled`, подменить `busy` на `loading`,
 * заменить настоящий замок оформлением.
 */

const ROOT = new URL('..', import.meta.url).pathname
const page = readFileSync(resolve(ROOT, 'app/pages/app.vue'), 'utf8')
// ⚠ Комментарии вырезаются ПЕРЕД сопоставлением: в шаблоне два пояснения, почему `pointer-events-none`
// здесь не годится, и гард, краснеющий на объяснении дефекта, подталкивает удалить объяснение, а не
// дефект. Тот же приём уже применён в гардах имени продукта и оболочки лендинга.
const template = page.slice(page.indexOf('<template>')).replace(/<!--[\s\S]*?-->/g, '')

/** Разрушительные действия, которые обязаны гаснуть на время пачки. Список ПОИМЁННЫЙ: «проверить,
 *  что где-то есть :disabled="busy"» проходило бы и когда половина кнопок его потеряла. */
const LOCKED_BY_BUSY = [
  'Настройки импорта', // шестерёнка: открыть настройки посреди пачки — сменить цель на середине
  'Очистить список',
  'Да, очистить',
  'Сбросить',
  'Да, обнулить'
]

describe('#443/#475: экран на время пачки блокируется по-настоящему', () => {
  it('замок не держится на `pointer-events-none` — это блокировка только для мыши', () => {
    // `opacity` как ОФОРМЛЕНИЕ разрешена и остаётся; запрещён именно замок указателем.
    expect(template).not.toMatch(/pointer-events-none/)
  })

  for (const label of LOCKED_BY_BUSY) {
    it(`«${label}» гаснет по busy`, () => {
      // Берём окно вокруг подписи: у B24Button атрибуты идут в произвольном порядке, а сама подпись
      // приходит либо `label="…"`, либо `:aria-label="busy ? …"`.
      const at = template.indexOf(label)
      expect(at, `подписи «${label}» на экране нет — гард сторожит несуществующую кнопку`).toBeGreaterThan(-1)
      const window = template.slice(Math.max(0, at - 700), at + 700)
      expect(window, `«${label}» должна нести :disabled c busy`).toMatch(/:disabled="[^"]*busy[^"]*"/)
    })
  }

  it('шестерёнка объявляет причину блокировки голосом, а не только гаснет', () => {
    // Погасшая кнопка без объяснения для скринридера — просто пропавшее действие.
    expect(template).toMatch(/:aria-label="busy \?/)
  })
})
