import { readFileSync } from 'node:fs'
import { describe, expect, it } from 'vitest'
import { LANDING_INTEGRATORS, LANDING_SOURCES, LANDING_WHY_SUBTITLE } from '../app/utils/landing'

// #96. Работа на сервере клиента звучала как ГОТОВАЯ услуга: «развернём приложение на вашем
// сервере», «развернём в вашем контуре», «доработаем и развернём», «установку в ваш контур берём на
// себя» — при том что ни договорной формы, ни разделения ответственности за хостинг, ни тарифа нет.
// Решение владельца: направление остаётся, обещание становится «по запросу».
//
// Второе, и важнее: **свой сервер не делает контур замкнутым** — разбор документа всё равно делает
// языковая модель поставщика. Оговорка про это стояла ТОЛЬКО в портальном виджете, то есть её
// видели уже установившие приложение. Лендинг читают ДО установки.

const read = (p: string) => readFileSync(new URL(`../${p}`, import.meta.url), 'utf8')

/**
 * Обещание живёт в НАКЛОНЕНИИ — «мы это сделаем», — а не в корне одного слова.
 *
 * ⚠ Первая версия гарда пинила только «развернём», и разбор снёс её мутациями: «поставим», «внедрим»,
 * «установку… берём на себя» проходили насквозь, то есть гард не мешал вернуть ровно то, что убрали.
 * Поэтому здесь перечислены формы 1 л. мн. ч. будущего времени и оборот принятия ответственности.
 *
 * ⚠ Инфинитивов тут намеренно НЕТ: «это может работать и на вашем сервере» описывает возможность
 * продукта, а не обязательство исполнителя — запрещать его значило бы запретить говорить о функции.
 *
 * ⚠ Граница слова — `(?![а-яё])`, а НЕ `\b`: `\b` в JS считает словом только ASCII, поэтому после
 * кириллического «м» границы не возникает вовсе и весь список молча не срабатывал. Проверено
 * мутациями: «Поставим приложение», «внедрим под ваш процесс» проходили насквозь.
 */
const PROMISE = /(развернём|развернем|поставим|установим|внедрим|перенесём|перенесем|разворачиваем)(?![а-яё])|бер[её]м\s+на\s+себя\s+установ|установку[^.]{0,40}бер[её]м\s+на\s+себя/i

/** Тексты лендинга целиком — обещание могло вернуться в любую строку, не только в три известные. */
const LANDING_TEXTS = 'app/utils/landing.ts'

describe('#96: работа на своём сервере — по запросу, а не готовая услуга', () => {
  it('ни одна строка текстов лендинга не обещает сделать это за клиента', () => {
    // По ВСЕМУ файлу, а не по трём выбранным константам: подзаголовок «Почему мы» разбор нашёл
    // именно так — он обещал сильнее соседей («берём на себя») и стоял выше оговорки.
    const src = read(LANDING_TEXTS)
    const offenders = src.split('\n').filter(l => !l.trim().startsWith('//') && PROMISE.test(l))
    expect(offenders, `обещание вернулось: ${offenders.join(' | ')}`).toEqual([])
  })

  it('и разметка лендинга тоже', () => {
    expect(read('app/pages/index.vue')).not.toMatch(PROMISE)
  })

  it('портальный виджет тоже', () => {
    expect(read('app/components/SelfHostedPromo.vue')).not.toMatch(PROMISE)
  })

  it('коммерческий документ не называет это готовой услугой с прайсом', () => {
    // Главный носитель обещания «с ценой»: лендинг говорит «по запросу», а документ, который уходит
    // клиенту следом, называл фикс-цену за «продуктизированную» услугу. Расхождение хуже исходного.
    const pricing = read('docs/PRICING.md')
    expect(pricing).not.toMatch(/готовые фикс-пакеты \(продуктизировано\)/i)
    expect(pricing, 'нет пометки «по запросу» рядом с ценами переноса').toMatch(/по запросу.{0,400}не публичное предложение/is)
  })

  it('но направление не исчезло — путь «напишите, обсудим» остался', () => {
    // Убрать обещание и заодно убрать предложение — не то же самое: раздел существует ради заявок.
    expect(LANDING_SOURCES.text).toMatch(/по запросу/i)
    expect(LANDING_INTEGRATORS).toMatch(/готовы обсудить/i)
    expect(LANDING_WHY_SUBTITLE).toMatch(/готовы обсудить/i)
    expect(read('app/components/SelfHostedPromo.vue')).toMatch(/напишите нам/i)
  })
})

describe('#96: оговорка про внешний разбор видна ДО установки', () => {
  /** Смысл, а не буква: две формулировки в двух местах не должны быть пришиты к одной строке. */
  const MEANING = /не делает контур замкнутым/i

  it('лежит в текстах лендинга и ВЫВОДИТСЯ на странице', () => {
    expect(LANDING_SOURCES.note).toMatch(MEANING)
    const page = read('app/pages/index.vue')
    // ⚠ Проверяем вывод, а не только упоминание: константа, которую никто не рендерит, — это ровно
    // то состояние, из которого дефект и вырос.
    expect(page).toContain('LANDING_SOURCES.note')
    // …и что её не спрятали. Мутация «отрендерить, но `hidden`» проходила незамеченной.
    const block = page.slice(page.indexOf('LANDING_SOURCES.note') - 300, page.indexOf('LANDING_SOURCES.note'))
    expect(block, 'оговорка скрыта классом').not.toMatch(/\b(hidden|sr-only|opacity-0)\b/)
  })

  it('не бледнее и не мельче основного текста блока', () => {
    // Утверждение существует ровно затем, чтобы человек НЕ ушёл с ложным выводом. «Мелкий шрифт под
    // договором» для него — неверный приём, и запас по контрасту у `white/50` был всего ~15%.
    const page = read('app/pages/index.vue')
    const i = page.indexOf('LANDING_SOURCES.note')
    const cls = page.slice(page.lastIndexOf('<p', i), i)
    expect(cls).not.toMatch(/text-white\/(?:[0-5]?\d)\b/)
    expect(cls).not.toMatch(/text-xs/)
  })

  it('в портальном виджете оговорка тоже осталась — и говорит то же самое', () => {
    // Она была там раньше и должна пережить правку формулировок: «наводя порядок», единственное
    // честное предложение легко вычистить вместе с обещанием. Сверяем СМЫСЛ, иначе гард запрещал бы
    // привести два текста к одной формулировке.
    expect(read('app/components/SelfHostedPromo.vue')).toMatch(MEANING)
  })
})
