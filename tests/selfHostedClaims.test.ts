import { readFileSync } from 'node:fs'
import { describe, expect, it } from 'vitest'
import { LANDING_INTEGRATORS, LANDING_SOURCES } from '../app/utils/landing'

// #96. Работа на сервере клиента звучала как готовая услуга: «развернём приложение на вашем
// сервере», «развернём в вашем контуре», «доработаем и развернём». Утвердительное наклонение в
// четырёх местах — а юридической модели, ответственности за хостинг и тарифа нет ни одного. Решение
// владельца: направление остаётся, обещание становится «по запросу».
//
// Второе, и важнее: **свой сервер не делает контур замкнутым** — разбор документа всё равно делает
// языковая модель поставщика. Оговорка про это стояла ТОЛЬКО в портальном виджете, то есть её
// видели уже установившие приложение. Лендинг читают ДО установки, и человек уходил с готовым
// выводом «свой сервер = данные никуда не уходят».

const read = (p: string) => readFileSync(new URL(`../${p}`, import.meta.url), 'utf8')

/** Слова, которыми обещают готовую услугу. Ищем формы «развернём/развернем», а не корень целиком:
 *  «разворачивается тема», «развёрнутый ответ» — не про это. */
const PROMISE = /развернём|развернем|разверн[уё]м/i

describe('#96: работа на своём сервере — по запросу, а не готовая услуга', () => {
  it('лендинг не обещает развернуть', () => {
    expect(LANDING_INTEGRATORS).not.toMatch(PROMISE)
    expect(LANDING_SOURCES.text).not.toMatch(PROMISE)
    expect(read('app/pages/index.vue')).not.toMatch(PROMISE)
  })

  it('портальный виджет тоже', () => {
    expect(read('app/components/SelfHostedPromo.vue')).not.toMatch(PROMISE)
  })

  it('но направление не исчезло — путь «напишите, обсудим» остался', () => {
    // Убрать обещание и заодно убрать предложение — не то же самое: раздел существует ради заявок.
    expect(LANDING_SOURCES.text).toMatch(/по запросу|индивидуальн/i)
    expect(LANDING_INTEGRATORS).toMatch(/индивидуальн|обсужда/i)
    expect(read('app/components/SelfHostedPromo.vue')).toMatch(/обсуждаем индивидуально/i)
  })
})

describe('#96: оговорка про внешний разбор видна ДО установки', () => {
  it('лежит в текстах лендинга и выводится на странице', () => {
    expect(LANDING_SOURCES.note).toBeTruthy()
    // ⚠ Проверяем ВЫВОД, а не только наличие строки: константа, которую никто не рендерит, — это
    // ровно то состояние, из которого дефект и вырос (оговорка была, но не там, где её читают).
    expect(read('app/pages/index.vue')).toContain('LANDING_SOURCES.note')
  })

  it('говорит главное: свой сервер не делает контур замкнутым', () => {
    expect(LANDING_SOURCES.note).toMatch(/не делает контур замкнутым/i)
    expect(LANDING_SOURCES.note).toMatch(/языковой модели|поставщик/i)
  })

  it('в портальном виджете оговорка тоже осталась', () => {
    // Она была там раньше и должна пережить правку формулировок — иначе, «наводя порядок»,
    // единственное честное предложение можно вычистить вместе с обещанием.
    expect(read('app/components/SelfHostedPromo.vue')).toMatch(/всё равно уходит на LLM-провайдера/i)
  })
})
